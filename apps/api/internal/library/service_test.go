func TestLibraryServiceResolve(t *testing.T) {
	env := openLibraryTestEnv(t)
	ctx := context.Background()

	saved := mustSaveAsset(t, ctx, env.svc, env.wsA, "r1", "")
	results, err := env.svc.ResolveAssets(ctx, env.wsA, []V1ResolveItem{
		{Provider: "unsplash", SourceID: "r1"},
		{Provider: "unsplash", SourceID: "missing"},
		{Provider: "bogus", SourceID: "x"},
		{Provider: "unsplash", SourceURL: libraryTestAssetURL},
		{Provider: "unsplash", SourceURL: "https://images.unsplash.com/not-saved"},
		{Provider: "unsplash", SourceURL: "http://images.unsplash.com/photo-test"},
	})
	if err != nil {
		t.Fatal(err)
	}
	got := map[string]string{}
	for _, result := range results {
		key := result.Provider + "\x00" + result.SourceID
		got[key] = result.Status
	}
	if got["unsplash\x00r1"] != "resolved" || got["unsplash\x00missing"] != "unresolved" || got["bogus\x00x"] != "unresolved" {
		t.Fatalf("resolve statuses = %v", got)
	}
	if results[0].Asset == nil || results[0].Asset.PublicID != saved.PublicID {
		t.Fatalf("resolved asset = %+v, want %s", results[0].Asset, saved.PublicID)
	}
	if results[3].Status != "resolved" || results[3].SourceID != "r1" {
		t.Fatalf("url resolve = %+v, want resolved r1", results[3])
	}
	if results[4].Status != "unresolved" || results[5].Status != "unresolved" {
		t.Fatalf("bad url resolves = %+v, want unresolved", results[4:6])
	}

	many := make([]V1ResolveItem, 0, V1MaxResolveItems+1)
	for i := 0; i <= V1MaxResolveItems; i++ {
		many = append(many, V1ResolveItem{Provider: "unsplash", SourceID: fmt.Sprintf("b%d", i)})
	}
	if _, err := env.svc.ResolveAssets(ctx, env.wsA, many); !errors.Is(err, ErrV1ResolveTooMany) {
		t.Fatalf("oversize resolve = %v, want too many", err)
	}
}

