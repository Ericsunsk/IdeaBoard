	t.Helper()
	publicID, err := domain.NewV1AssetPublicID()
	if err != nil {
		t.Fatal(err)
	}
	asset, created, err := svc.SaveAsset(ctx, ws, domain.V1SaveAssetInput{FolderPublicID: folderID, Asset: libraryTestAssetInput(sourceID)}, publicID)
