CREATE FUNCTION validate_reward_code_mode()
RETURNS TRIGGER AS $$
DECLARE
  campaign_mode TEXT;
BEGIN
  EXECUTE pg_catalog.format(
    'SELECT mode FROM %I.reward_campaigns WHERE id = $1',
    TG_TABLE_SCHEMA
  ) INTO campaign_mode USING NEW.campaign_id;
  IF campaign_mode = 'public' AND NEW.batch_id IS NOT NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'IB505', MESSAGE = 'public Campaign cannot contain Batch Codes';
  END IF;
  IF campaign_mode = 'single_use' AND NEW.batch_id IS NULL THEN
    RAISE EXCEPTION USING ERRCODE = 'IB505', MESSAGE = 'single-use Campaign requires Batch Codes';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SET search_path = pg_catalog;
