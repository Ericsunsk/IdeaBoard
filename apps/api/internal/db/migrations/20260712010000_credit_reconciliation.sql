CREATE TABLE credit_reconciliation_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status VARCHAR(16) NOT NULL DEFAULT 'queued',
  requested_by BIGINT NOT NULL CHECK (requested_by > 0),
  stale_hold_after INTERVAL NOT NULL DEFAULT INTERVAL '24 hours' CHECK (stale_hold_after > INTERVAL '0'),
  finding_count BIGINT NOT NULL DEFAULT 0 CHECK (finding_count >= 0),
  critical_count BIGINT NOT NULL DEFAULT 0 CHECK (critical_count >= 0),
  isolated_wallet_count BIGINT NOT NULL DEFAULT 0 CHECK (isolated_wallet_count >= 0),
  attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  error_message TEXT NOT NULL DEFAULT '',
  requested_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  started_at TIMESTAMPTZ(3),
  completed_at TIMESTAMPTZ(3),
  CONSTRAINT ck_credit_reconciliation_run_status CHECK (status IN ('queued', 'running', 'completed', 'failed')),
  CONSTRAINT ck_credit_reconciliation_run_timestamps CHECK (
    (status = 'queued' AND completed_at IS NULL)
    OR (status = 'running' AND started_at IS NOT NULL AND completed_at IS NULL)
    OR (status IN ('completed', 'failed') AND started_at IS NOT NULL AND completed_at IS NOT NULL)
  )
);

CREATE UNIQUE INDEX uq_credit_reconciliation_active_run
  ON credit_reconciliation_runs ((TRUE)) WHERE status IN ('queued', 'running');
CREATE INDEX idx_credit_reconciliation_runs_requested_at
  ON credit_reconciliation_runs (id DESC);

CREATE TABLE credit_reconciliation_findings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fingerprint CHAR(64) NOT NULL UNIQUE CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
  finding_type VARCHAR(64) NOT NULL,
  severity VARCHAR(16) NOT NULL,
  risk VARCHAR(16) NOT NULL,
  wallet_user_id BIGINT REFERENCES credit_wallets(user_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  subject_type VARCHAR(32) NOT NULL,
  subject_id VARCHAR(160) NOT NULL,
  details JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details) = 'object'),
  status VARCHAR(16) NOT NULL DEFAULT 'open',
  isolated BOOLEAN NOT NULL DEFAULT FALSE,
  first_seen_run_id BIGINT NOT NULL REFERENCES credit_reconciliation_runs(id) ON DELETE RESTRICT,
  last_seen_run_id BIGINT NOT NULL REFERENCES credit_reconciliation_runs(id) ON DELETE RESTRICT,
  occurrence_count BIGINT NOT NULL DEFAULT 1 CHECK (occurrence_count > 0),
  first_seen_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  last_seen_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  resolved_at TIMESTAMPTZ(3),
  CONSTRAINT ck_credit_reconciliation_finding_severity CHECK (severity IN ('warning', 'error', 'critical')),
  CONSTRAINT ck_credit_reconciliation_finding_risk CHECK (risk IN ('low', 'high')),
  CONSTRAINT ck_credit_reconciliation_finding_status CHECK (status IN ('open', 'resolved')),
  CONSTRAINT ck_credit_reconciliation_finding_resolution CHECK (
    (status = 'open' AND resolved_at IS NULL) OR (status = 'resolved' AND resolved_at IS NOT NULL)
  )
);

CREATE INDEX idx_credit_reconciliation_findings_list
  ON credit_reconciliation_findings (status, id DESC);
CREATE INDEX idx_credit_reconciliation_findings_wallet
  ON credit_reconciliation_findings (wallet_user_id, id DESC) WHERE wallet_user_id IS NOT NULL;

CREATE TABLE credit_reconciliation_run_findings (
  run_id BIGINT NOT NULL REFERENCES credit_reconciliation_runs(id) ON DELETE RESTRICT,
  finding_id BIGINT NOT NULL REFERENCES credit_reconciliation_findings(id) ON DELETE RESTRICT,
  observed_severity VARCHAR(16) NOT NULL DEFAULT 'warning' CHECK (observed_severity IN ('warning', 'error', 'critical')),
  observed_risk VARCHAR(16) NOT NULL DEFAULT 'low' CHECK (observed_risk IN ('low', 'high')),
  observed_details JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(observed_details) = 'object'),
  observed_status VARCHAR(16) NOT NULL DEFAULT 'open' CHECK (observed_status IN ('open', 'resolved')),
  observed_isolated BOOLEAN NOT NULL DEFAULT FALSE,
  observed_occurrence_count BIGINT NOT NULL DEFAULT 1 CHECK (observed_occurrence_count > 0),
  observed_first_seen_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  observed_last_seen_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  observed_resolved_at TIMESTAMPTZ(3),
  PRIMARY KEY (run_id, finding_id)
);

CREATE TABLE credit_reconciliation_alerts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  finding_id BIGINT NOT NULL UNIQUE REFERENCES credit_reconciliation_findings(id) ON DELETE RESTRICT,
  wallet_user_id BIGINT REFERENCES credit_wallets(user_id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  severity VARCHAR(16) NOT NULL CHECK (severity IN ('error', 'critical')),
  status VARCHAR(16) NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'resolved')),
  payload JSONB NOT NULL CHECK (jsonb_typeof(payload) = 'object'),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp()
);

