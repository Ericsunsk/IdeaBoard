-- Identity admin reconciliation (dry-run alerting only).
--
-- Append-only migration: adds the runs/findings tables consumed by the
-- Identity admin reconciliation job. The scan only writes runs/findings
-- rows and emits slog alerts; automatic remediation is intentionally
-- absent in this phase.

CREATE TABLE identity_admin_reconciliation_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status VARCHAR(16) NOT NULL DEFAULT 'queued',
  trigger_type VARCHAR(16) NOT NULL,
  requested_by BIGINT,
  reason VARCHAR(1000),
  scheduled_for TIMESTAMPTZ(3),
  finding_count BIGINT NOT NULL DEFAULT 0 CHECK (finding_count >= 0),
  attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  error_message TEXT NOT NULL DEFAULT '',
  requested_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  started_at TIMESTAMPTZ(3),
  completed_at TIMESTAMPTZ(3),
  CONSTRAINT ck_identity_admin_recon_run_trigger CHECK (trigger_type IN ('manual', 'scheduled')),
  CONSTRAINT ck_identity_admin_recon_run_audit CHECK (
    (
      trigger_type = 'manual'
      AND requested_by IS NOT NULL
      AND requested_by > 0
      AND reason IS NOT NULL
      AND reason = btrim(reason, E' \t\n\r\f')
      AND char_length(reason) BETWEEN 1 AND 1000
      AND scheduled_for IS NULL
    )
    OR
    (
      trigger_type = 'scheduled'
      AND requested_by IS NULL
      AND reason IS NULL
      AND scheduled_for IS NOT NULL
    )
  ),
  CONSTRAINT ck_identity_admin_recon_run_status CHECK (status IN ('queued', 'running', 'completed', 'failed')),
  CONSTRAINT ck_identity_admin_recon_run_timestamps CHECK (
    (status = 'queued' AND completed_at IS NULL)
    OR (status = 'running' AND started_at IS NOT NULL AND completed_at IS NULL)
    OR (status IN ('completed', 'failed') AND started_at IS NOT NULL AND completed_at IS NOT NULL)
  )
);

CREATE UNIQUE INDEX uq_identity_admin_recon_active_run
  ON identity_admin_reconciliation_runs ((TRUE)) WHERE status IN ('queued', 'running');
CREATE UNIQUE INDEX uq_identity_admin_recon_scheduled_for
  ON identity_admin_reconciliation_runs (scheduled_for) WHERE trigger_type = 'scheduled';
CREATE INDEX idx_identity_admin_recon_runs_requested_at
  ON identity_admin_reconciliation_runs (id DESC);

CREATE TABLE identity_admin_reconciliation_findings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fingerprint CHAR(64) NOT NULL UNIQUE CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
  finding_type VARCHAR(64) NOT NULL,
  severity VARCHAR(16) NOT NULL,
  risk VARCHAR(16) NOT NULL,
  user_id BIGINT REFERENCES users(id) ON UPDATE RESTRICT ON DELETE SET NULL,
  subject_type VARCHAR(32) NOT NULL,
  subject_id VARCHAR(160) NOT NULL,
  details JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details) = 'object'),
  status VARCHAR(16) NOT NULL DEFAULT 'open',
  first_seen_run_id BIGINT NOT NULL REFERENCES identity_admin_reconciliation_runs(id) ON DELETE RESTRICT,
  last_seen_run_id BIGINT NOT NULL REFERENCES identity_admin_reconciliation_runs(id) ON DELETE RESTRICT,
  occurrence_count BIGINT NOT NULL DEFAULT 1 CHECK (occurrence_count > 0),
  first_seen_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  last_seen_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  resolved_at TIMESTAMPTZ(3),
  CONSTRAINT ck_identity_admin_recon_finding_severity CHECK (severity IN ('warning', 'error', 'critical')),
  CONSTRAINT ck_identity_admin_recon_finding_risk CHECK (risk IN ('low', 'high')),
  CONSTRAINT ck_identity_admin_recon_finding_status CHECK (status IN ('open', 'resolved')),
  CONSTRAINT ck_identity_admin_recon_finding_resolution CHECK (
    (status = 'open' AND resolved_at IS NULL) OR (status = 'resolved' AND resolved_at IS NOT NULL)
  )
);

CREATE INDEX idx_identity_admin_recon_findings_list
  ON identity_admin_reconciliation_findings (status, id DESC);
CREATE INDEX idx_identity_admin_recon_findings_user
  ON identity_admin_reconciliation_findings (user_id, id DESC) WHERE user_id IS NOT NULL;

CREATE TABLE identity_admin_reconciliation_run_findings (
  run_id BIGINT NOT NULL REFERENCES identity_admin_reconciliation_runs(id) ON DELETE RESTRICT,
  finding_id BIGINT NOT NULL REFERENCES identity_admin_reconciliation_findings(id) ON DELETE RESTRICT,
  observed_severity VARCHAR(16) NOT NULL DEFAULT 'warning' CHECK (observed_severity IN ('warning', 'error', 'critical')),
  observed_risk VARCHAR(16) NOT NULL DEFAULT 'low' CHECK (observed_risk IN ('low', 'high')),
  observed_details JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(observed_details) = 'object'),
  observed_status VARCHAR(16) NOT NULL DEFAULT 'open' CHECK (observed_status IN ('open', 'resolved')),
  observed_occurrence_count BIGINT NOT NULL DEFAULT 1 CHECK (observed_occurrence_count > 0),
  observed_first_seen_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  observed_last_seen_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  observed_resolved_at TIMESTAMPTZ(3),
  PRIMARY KEY (run_id, finding_id)
);

CREATE FUNCTION start_identity_admin_reconciliation(
  p_trigger_type TEXT,
  p_requested_by BIGINT,
  p_reason TEXT,
  p_scheduled_for TIMESTAMPTZ,
  p_only_if_overdue BOOLEAN
)
RETURNS TABLE (run_id BIGINT, enqueue_required BOOLEAN) AS $$
DECLARE
  v_run_id BIGINT;
  v_run_status VARCHAR(16);
BEGIN
  p_trigger_type := btrim(p_trigger_type);
  p_reason := NULLIF(btrim(p_reason, E' \t\n\r\f'), '');
  IF p_trigger_type IS NULL
     OR p_only_if_overdue IS NULL
     OR (
       p_trigger_type = 'manual'
       AND (
         p_requested_by IS NULL OR p_requested_by <= 0
         OR p_reason IS NULL OR char_length(p_reason) > 1000
         OR p_scheduled_for IS NOT NULL
         OR p_only_if_overdue
       )
     )
     OR (
       p_trigger_type = 'scheduled'
       AND (
         p_requested_by IS NOT NULL
         OR p_reason IS NOT NULL
         OR p_scheduled_for IS NULL
       )
     )
     OR p_trigger_type NOT IN ('manual', 'scheduled') THEN
    RAISE EXCEPTION USING ERRCODE = 'IB311', MESSAGE = 'invalid identity admin reconciliation request';
  END IF;

  PERFORM pg_advisory_xact_lock(5283921922134398291);

  IF p_only_if_overdue AND EXISTS (
    SELECT 1
    FROM identity_admin_reconciliation_runs
    WHERE status = 'completed'
      AND completed_at >= clock_timestamp() - INTERVAL '24 hours'
  ) THEN
    RETURN QUERY SELECT NULL::BIGINT, FALSE;
    RETURN;
  END IF;

  SELECT runs.id INTO v_run_id
  FROM identity_admin_reconciliation_runs runs
  WHERE runs.status IN ('queued', 'running')
  ORDER BY runs.id DESC
  LIMIT 1;
  IF FOUND THEN
    RETURN QUERY SELECT v_run_id, FALSE;
    RETURN;
  END IF;

  IF p_trigger_type = 'scheduled' THEN
    SELECT runs.id, runs.status INTO v_run_id, v_run_status
    FROM identity_admin_reconciliation_runs runs
    WHERE runs.trigger_type = 'scheduled'
      AND runs.scheduled_for = p_scheduled_for;
    IF FOUND THEN
      IF p_only_if_overdue AND v_run_status = 'failed' THEN
        UPDATE identity_admin_reconciliation_runs
        SET status = 'queued',
            error_message = '',
            started_at = NULL,
            completed_at = NULL
        WHERE id = v_run_id;
        RETURN QUERY SELECT v_run_id, TRUE;
        RETURN;
      END IF;
      RETURN QUERY SELECT v_run_id, FALSE;
      RETURN;
    END IF;
  END IF;

  INSERT INTO identity_admin_reconciliation_runs (
    trigger_type,
    requested_by,
    reason,
    scheduled_for
  )
  VALUES (
    p_trigger_type,
    p_requested_by,
    p_reason,
    p_scheduled_for
  )
  RETURNING id INTO v_run_id;

  RETURN QUERY SELECT v_run_id, TRUE;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog;

CREATE FUNCTION fail_identity_admin_reconciliation(p_run_id BIGINT, p_error TEXT)
RETURNS VOID AS $$
BEGIN
  UPDATE identity_admin_reconciliation_runs
  SET status = 'failed', started_at = COALESCE(started_at, clock_timestamp()), completed_at = clock_timestamp(),
      error_message = left(COALESCE(p_error, ''), 2000)
  WHERE id = p_run_id AND status IN ('queued', 'running');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog;

REVOKE ALL ON FUNCTION start_identity_admin_reconciliation(TEXT, BIGINT, TEXT, TIMESTAMPTZ, BOOLEAN) FROM PUBLIC;
REVOKE ALL ON FUNCTION fail_identity_admin_reconciliation(BIGINT, TEXT) FROM PUBLIC;

-- Bind the new privileged routines to the installed schema, mirroring the
-- bootstrap hardening block: every SECURITY DEFINER routine resolves
-- tables through the installing schema first.
DO $$
DECLARE trusted_schema TEXT := current_schema();
BEGIN
  EXECUTE format(
    'ALTER FUNCTION %I.start_identity_admin_reconciliation(TEXT, BIGINT, TEXT, TIMESTAMPTZ, BOOLEAN) SET search_path TO %I, pg_catalog, pg_temp',
    trusted_schema, trusted_schema
  );
  EXECUTE format(
    'ALTER FUNCTION %I.fail_identity_admin_reconciliation(BIGINT, TEXT) SET search_path TO %I, pg_catalog, pg_temp',
    trusted_schema, trusted_schema
  );
END;
$$;
