CREATE TABLE provider_endpoint_models (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  provider_endpoint_id BIGINT NOT NULL,
  model_name VARCHAR(128) NOT NULL,
  supports_2k BOOLEAN NOT NULL DEFAULT FALSE,
  supports_4k BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT fk_provider_endpoint_models_endpoint_id FOREIGN KEY (provider_endpoint_id) REFERENCES provider_endpoints(id) ON DELETE CASCADE,
  CONSTRAINT chk_provider_endpoint_models_name_not_blank CHECK (btrim(model_name) <> '')
);

CREATE UNIQUE INDEX uq_provider_endpoint_models_endpoint_model_lower
  ON provider_endpoint_models (provider_endpoint_id, lower(model_name));
CREATE INDEX idx_provider_endpoint_models_endpoint_id
  ON provider_endpoint_models (provider_endpoint_id);

INSERT INTO provider_endpoint_models (provider_endpoint_id, model_name)
SELECT DISTINCT a.provider_endpoint_id, m.model_name
FROM api_accounts AS a
JOIN api_account_models AS m ON m.account_id = a.id
WHERE a.deleted_at IS NULL
ON CONFLICT (provider_endpoint_id, lower(model_name)) DO NOTHING;

CREATE TRIGGER set_provider_endpoint_models_updated_at
BEFORE UPDATE ON provider_endpoint_models
FOR EACH ROW EXECUTE FUNCTION set_updated_at();
