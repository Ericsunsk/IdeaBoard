  completed_at TIMESTAMPTZ NULL,
  expires_at TIMESTAMPTZ NOT NULL DEFAULT (now() + INTERVAL '24 hours'),
  attempt_token TEXT NOT NULL DEFAULT gen_random_uuid()::text,
  settlement_unknown BOOLEAN NOT NULL DEFAULT FALSE,
