-- Service Model Pool persistence (#848, ADR-0012).
--
-- Mirrors internal/db/schema/fragments/modelpool.sql. Fresh replay and
-- incremental apply both end at the fragment-defined shape.
--
-- A Service owns exactly one Model pool (unordered entries, no
-- priority/fallback/weight). Entry capabilities accept only 1k/2k/4k;
-- There is no default resolution; every request and capability uses 1k,
-- 2k, or 4k. Pool version starts at 1 on first pool write.
-- tasks.routing_snapshot is nullable so pre-pool tasks stay readable.
-- task_execution_attempts retry columns are ''/0 until wave 2 writes them.

CREATE TABLE service_model_pool_entry (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  service TEXT NOT NULL,
  model_id TEXT NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT uq_service_model_pool_entry_service_model UNIQUE (service, model_id),
  CONSTRAINT ck_service_model_pool_entry_service CHECK (length(btrim(service)) BETWEEN 1 AND 64),
  CONSTRAINT ck_service_model_pool_entry_model_id CHECK (length(btrim(model_id)) BETWEEN 1 AND 128)
);

CREATE INDEX idx_service_model_pool_entry_service ON service_model_pool_entry (service);

CREATE TABLE service_model_pool_resolution (
  pool_entry_id BIGINT NOT NULL REFERENCES service_model_pool_entry(id) ON DELETE CASCADE,
  resolution TEXT NOT NULL,
  CONSTRAINT pk_service_model_pool_resolution PRIMARY KEY (pool_entry_id, resolution),
  CONSTRAINT ck_service_model_pool_resolution_value CHECK (resolution IN ('1k', '2k', '4k'))
);

CREATE INDEX idx_service_model_pool_resolution_resolution ON service_model_pool_resolution (resolution);

CREATE TABLE service_model_pool_version (
  service TEXT PRIMARY KEY,
  version BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT ck_service_model_pool_version_service CHECK (length(btrim(service)) BETWEEN 1 AND 64),
  CONSTRAINT ck_service_model_pool_version_value CHECK (version >= 1)
);

ALTER TABLE tasks
  ADD COLUMN routing_snapshot JSONB NULL,
  ADD CONSTRAINT chk_tasks_routing_snapshot CHECK (routing_snapshot IS NULL OR jsonb_typeof(routing_snapshot) = 'object');

ALTER TABLE task_execution_attempts
  ADD COLUMN retry_layer TEXT NOT NULL DEFAULT '',
  ADD COLUMN gateway_retry_count INTEGER NOT NULL DEFAULT 0,
  ADD CONSTRAINT ck_task_execution_attempts_retry_layer CHECK (retry_layer IN ('', 'gateway', 'model_fallback', 'river_task')),
  ADD CONSTRAINT ck_task_execution_attempts_gateway_retry_count CHECK (gateway_retry_count >= 0);

CREATE INDEX idx_task_execution_attempts_retry_layer ON task_execution_attempts (retry_layer) WHERE retry_layer <> '';

-- Resolution contract cleanup (#848): the legacy default variant is not a
-- valid billing or task fact. Existing clean-cut data is canonicalized to
-- 1k before the checks are tightened. A deployment with both a legacy
-- default row and an existing 1k row for the same key must resolve that
-- duplicate explicitly rather than silently choose a price.
DO $$
BEGIN
  IF EXISTS (
    SELECT 1
    FROM billing_price_versions legacy
    JOIN billing_price_versions canonical
      ON canonical.sku = legacy.sku
     AND canonical.output_resolution = '1k'
     AND canonical.version = legacy.version
    WHERE legacy.output_resolution = 'default'
  ) THEN
    RAISE EXCEPTION 'cannot canonicalize duplicate billing default and 1k price versions';
  END IF;
  IF EXISTS (
    SELECT 1
    FROM billing_current_prices legacy
    JOIN billing_current_prices canonical
      ON canonical.sku = legacy.sku
     AND canonical.output_resolution = '1k'
    WHERE legacy.output_resolution = 'default'
  ) THEN
    RAISE EXCEPTION 'cannot canonicalize duplicate billing default and 1k current prices';
  END IF;
END
$$;

ALTER TABLE billing_current_prices
  DROP CONSTRAINT billing_current_prices_price_fkey,
  DROP CONSTRAINT billing_current_prices_resolution_check;
ALTER TABLE billing_price_versions
  DROP CONSTRAINT billing_price_versions_output_resolution_check;
ALTER TABLE task_billing_snapshots
  DROP CONSTRAINT task_billing_snapshots_output_resolution_check;

UPDATE billing_price_versions
SET output_resolution = '1k'
WHERE output_resolution = 'default';
UPDATE billing_current_prices
SET output_resolution = '1k'
WHERE output_resolution = 'default';
UPDATE task_billing_snapshots
SET output_resolution = '1k'
WHERE output_resolution = 'default';

ALTER TABLE billing_price_versions
  ADD CONSTRAINT billing_price_versions_output_resolution_check
    CHECK (output_resolution IN ('1k', '2k', '4k'));
ALTER TABLE billing_current_prices
  ADD CONSTRAINT billing_current_prices_resolution_check
    CHECK (output_resolution IN ('1k', '2k', '4k')),
  ADD CONSTRAINT billing_current_prices_price_fkey
    FOREIGN KEY (sku, output_resolution, price_version_id)
    REFERENCES billing_price_versions(sku, output_resolution, price_version_id)
    ON UPDATE RESTRICT ON DELETE RESTRICT;
ALTER TABLE task_billing_snapshots
  ADD CONSTRAINT task_billing_snapshots_output_resolution_check
    CHECK (output_resolution IN ('1k', '2k', '4k'));
