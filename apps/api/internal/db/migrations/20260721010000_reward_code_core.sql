CREATE TABLE reward_codes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  display_name VARCHAR(120) NOT NULL,
  key_version VARCHAR(32) NOT NULL,
  code_digest BYTEA NOT NULL,
  code_hint VARCHAR(4) NOT NULL,
  credit_amount BIGINT NOT NULL,
  max_redemptions BIGINT NOT NULL DEFAULT 0,
  redemption_count BIGINT NOT NULL DEFAULT 0,
  expires_at TIMESTAMPTZ(3),
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  created_by BIGINT NOT NULL,
  idempotency_key VARCHAR(128) NOT NULL,
  request_fingerprint BYTEA NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT uq_reward_codes_digest UNIQUE (key_version, code_digest),
  CONSTRAINT uq_reward_codes_creator_idempotency UNIQUE (created_by, idempotency_key),
  CONSTRAINT ck_reward_codes_name CHECK (
    display_name = btrim(display_name, E' \t\n\r\f') AND char_length(display_name) BETWEEN 1 AND 120
  ),
  CONSTRAINT ck_reward_codes_key_version CHECK (
    key_version = btrim(key_version) AND char_length(key_version) BETWEEN 1 AND 32
  ),
  CONSTRAINT ck_reward_codes_digest CHECK (octet_length(code_digest) = 32),
  CONSTRAINT ck_reward_codes_hint CHECK (code_hint ~ '^[A-Z0-9]{4}$'),
  CONSTRAINT ck_reward_codes_credit_amount CHECK (credit_amount BETWEEN 1 AND 9000000000000000),
  CONSTRAINT ck_reward_codes_capacity CHECK (
    redemption_count >= 0 AND (max_redemptions = 0 OR redemption_count <= max_redemptions)
  ),
  CONSTRAINT ck_reward_codes_idempotency CHECK (
    idempotency_key = btrim(idempotency_key, E' \t\n\r\f')
    AND char_length(idempotency_key) BETWEEN 1 AND 128
  ),
  CONSTRAINT ck_reward_codes_fingerprint CHECK (octet_length(request_fingerprint) = 32),
  CONSTRAINT fk_reward_codes_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE reward_code_digest_aliases (
  reward_code_id BIGINT NOT NULL,
  key_version VARCHAR(32) NOT NULL,
  code_digest BYTEA NOT NULL,
  CONSTRAINT pk_reward_code_digest_aliases PRIMARY KEY (key_version, code_digest),
  CONSTRAINT ck_reward_code_digest_aliases_key_version CHECK (
    key_version = btrim(key_version) AND char_length(key_version) BETWEEN 1 AND 32
  ),
  CONSTRAINT ck_reward_code_digest_aliases_digest CHECK (octet_length(code_digest) = 32),
  CONSTRAINT fk_reward_code_digest_aliases_code FOREIGN KEY (reward_code_id) REFERENCES reward_codes(id) ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE TABLE reward_redemptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reward_code_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  credit_amount BIGINT NOT NULL,
  credit_transaction_id VARCHAR(64) NOT NULL,
  available_balance_after BIGINT NOT NULL,
  redeemed_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  CONSTRAINT uq_reward_redemptions_user_code UNIQUE (user_id, reward_code_id),
  CONSTRAINT uq_reward_redemptions_credit_transaction UNIQUE (credit_transaction_id),
  CONSTRAINT ck_reward_redemptions_credit_amount CHECK (credit_amount BETWEEN 1 AND 9000000000000000),
  CONSTRAINT fk_reward_redemptions_code FOREIGN KEY (reward_code_id) REFERENCES reward_codes(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT fk_reward_redemptions_user FOREIGN KEY (user_id) REFERENCES users(id) ON UPDATE RESTRICT ON DELETE RESTRICT,
  CONSTRAINT fk_reward_redemptions_credit_transaction FOREIGN KEY (credit_transaction_id) REFERENCES credit_transactions(transaction_id) ON UPDATE RESTRICT ON DELETE RESTRICT
