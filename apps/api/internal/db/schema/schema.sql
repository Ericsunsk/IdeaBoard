CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(50) NOT NULL,
  auth_user_id VARCHAR(128),
  storage_uid CHAR(6) NOT NULL,
  avatar VARCHAR(1024) NOT NULL DEFAULT '',
  role VARCHAR(20) NOT NULL DEFAULT 'user',
  status SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uq_users_username UNIQUE (username),
  CONSTRAINT uq_users_auth_user_id UNIQUE (auth_user_id),
  CONSTRAINT uq_users_storage_uid UNIQUE (storage_uid)
);

CREATE TABLE users_used_uids (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  storage_uid CHAR(6) NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uq_users_used_uids_storage_uid UNIQUE (storage_uid)
);

CREATE TABLE api_accounts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  channel_id BIGINT NOT NULL DEFAULT 0,
  platform VARCHAR(50) NOT NULL,
  api_type VARCHAR(50) NOT NULL,
  model_set VARCHAR(255) NOT NULL DEFAULT '',
  api_key TEXT NOT NULL,
  proxy_url TEXT NOT NULL,
  max_concurrent INTEGER NOT NULL DEFAULT 3,
  timeout INTEGER NOT NULL DEFAULT 120,
  extra_config TEXT NOT NULL,
  status SMALLINT NOT NULL DEFAULT 1,
  fail_count INTEGER NOT NULL DEFAULT 0,
  weight INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);

CREATE INDEX idx_api_accounts_status ON api_accounts (status);
CREATE INDEX idx_api_accounts_channel_id ON api_accounts (channel_id);

CREATE TABLE tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id VARCHAR(64) NOT NULL,
  user_id BIGINT NOT NULL,
  channel_id BIGINT NOT NULL,
  account_id BIGINT NOT NULL DEFAULT 0,
  prompt TEXT NOT NULL,
  user_prompt TEXT NOT NULL,
  params TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  lease_token VARCHAR(128) NOT NULL DEFAULT '',
  retry_count INTEGER NOT NULL DEFAULT 0,
  error_msg TEXT NOT NULL,
  result TEXT NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ(3),
  CONSTRAINT uq_tasks_task_id UNIQUE (task_id)
);

CREATE INDEX idx_tasks_user_id ON tasks (user_id);
CREATE INDEX idx_tasks_account_id ON tasks (account_id);
CREATE INDEX idx_tasks_status ON tasks (status);
CREATE INDEX idx_tasks_lease_token ON tasks (lease_token);
CREATE INDEX idx_tasks_created_at ON tasks (created_at);
CREATE INDEX idx_tasks_running_account ON tasks (account_id) WHERE status = 'running';

CREATE TABLE task_execution_metrics (
  task_id VARCHAR(64) PRIMARY KEY,
  current_stage VARCHAR(32) NOT NULL DEFAULT 'queued',
  bottleneck_source VARCHAR(32) NOT NULL DEFAULT 'unknown',
  failure_stage VARCHAR(32) NOT NULL DEFAULT '',
  failure_category VARCHAR(64) NOT NULL DEFAULT '',
  assigned_at TIMESTAMPTZ(3),
  provider_started_at TIMESTAMPTZ(3),
  provider_finished_at TIMESTAMPTZ(3),
  finalize_started_at TIMESTAMPTZ(3),
  finalize_finished_at TIMESTAMPTZ(3),
  queue_wait_ms BIGINT NOT NULL DEFAULT 0,
  worker_overhead_ms BIGINT NOT NULL DEFAULT 0,
  provider_latency_ms BIGINT NOT NULL DEFAULT 0,
  finalize_latency_ms BIGINT NOT NULL DEFAULT 0,
  total_latency_ms BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT fk_task_execution_metrics_task_id FOREIGN KEY (task_id) REFERENCES tasks(task_id) ON DELETE CASCADE
);

CREATE INDEX idx_task_execution_metrics_current_stage ON task_execution_metrics (current_stage);
CREATE INDEX idx_task_execution_metrics_bottleneck_source ON task_execution_metrics (bottleneck_source);
CREATE INDEX idx_task_execution_metrics_failure_category ON task_execution_metrics (failure_category);

CREATE TABLE task_cancellations (
  task_id VARCHAR(64) PRIMARY KEY,
  expires_at TIMESTAMPTZ(3) NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);

CREATE INDEX idx_task_cancellations_expires_at ON task_cancellations (expires_at);

CREATE TABLE task_outputs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id VARCHAR(64) NOT NULL,
  role VARCHAR(32) NOT NULL DEFAULT 'image',
  url TEXT NOT NULL,
  storage_key TEXT NOT NULL,
  mime_type VARCHAR(64) NOT NULL DEFAULT '',
  width INTEGER NOT NULL DEFAULT 0,
  height INTEGER NOT NULL DEFAULT 0,
  size_bytes BIGINT NOT NULL DEFAULT 0,
  sort_index INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT fk_task_outputs_task_id FOREIGN KEY (task_id) REFERENCES tasks(task_id) ON DELETE CASCADE
);

CREATE INDEX idx_task_outputs_task_sort ON task_outputs (task_id, sort_index);

CREATE TABLE task_daily_stats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stat_date CHAR(10) NOT NULL,
  model_name VARCHAR(128) NOT NULL DEFAULT '',
  user_key VARCHAR(128) NOT NULL DEFAULT '',
  total BIGINT NOT NULL DEFAULT 0,
  completed BIGINT NOT NULL DEFAULT 0,
  failed BIGINT NOT NULL DEFAULT 0,
  latency_seconds_sum DOUBLE PRECISION NOT NULL DEFAULT 0,
  latency_count BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uq_task_daily_stat UNIQUE (stat_date, model_name, user_key)
);

CREATE TABLE task_stat_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id VARCHAR(64) NOT NULL,
  stat_date CHAR(10) NOT NULL,
  model_name VARCHAR(128) NOT NULL DEFAULT '',
  user_key VARCHAR(128) NOT NULL DEFAULT '',
  status VARCHAR(20) NOT NULL,
  latency_seconds DOUBLE PRECISION NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uq_task_stat_event_task_id UNIQUE (task_id)
);

CREATE INDEX idx_task_stat_events_stat_date ON task_stat_events (stat_date);

CREATE TABLE task_daily_stat_backfills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stat_date CHAR(10) NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uq_task_daily_stat_backfill_date UNIQUE (stat_date)
);

