CREATE OR REPLACE FUNCTION prevent_api_account_channel_change()
RETURNS trigger AS $$
BEGIN
  IF NEW.channel_id IS DISTINCT FROM OLD.channel_id THEN
    RAISE EXCEPTION 'api_accounts.channel_id is immutable; create a new account to switch channels';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER prevent_api_account_channel_change BEFORE UPDATE OF channel_id ON api_accounts FOR EACH ROW EXECUTE FUNCTION prevent_api_account_channel_change();

