BEFORE UPDATE ON credit_accounts
FOR EACH ROW EXECUTE FUNCTION guard_credit_account_projection();

CREATE OR REPLACE FUNCTION apply_credit_posting_balances()
RETURNS trigger AS $$
DECLARE
  posting_delta RECORD;
BEGIN
  FOR posting_delta IN
    SELECT account_id, asset_code, SUM(amount)::BIGINT AS amount
    FROM inserted_credit_postings
    GROUP BY account_id, asset_code
    ORDER BY account_id
  LOOP
    UPDATE credit_accounts
    SET balance = balance + posting_delta.amount
    WHERE id = posting_delta.account_id
      AND asset_code = posting_delta.asset_code;
    IF NOT FOUND THEN
      RAISE EXCEPTION 'credit account % for asset % does not exist', posting_delta.account_id, posting_delta.asset_code;
    END IF;
  END LOOP;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog;

CREATE TRIGGER apply_credit_posting_balances
AFTER INSERT ON credit_postings
REFERENCING NEW TABLE AS inserted_credit_postings
FOR EACH STATEMENT EXECUTE FUNCTION apply_credit_posting_balances();

CREATE OR REPLACE FUNCTION validate_credit_transaction_balance()
RETURNS trigger AS $$
DECLARE
  checked_transaction_id VARCHAR(64);
  expected_count SMALLINT;
  expected_asset VARCHAR(32);
  actual_count BIGINT;
  actual_total NUMERIC;
  actual_assets BIGINT;
BEGIN
  checked_transaction_id := NEW.transaction_id;
  SELECT posting_count, asset_code
  INTO expected_count, expected_asset
  FROM credit_transactions
  WHERE transaction_id = checked_transaction_id;

  SELECT COUNT(*), COALESCE(SUM(amount), 0), COUNT(DISTINCT asset_code)
  INTO actual_count, actual_total, actual_assets
  FROM credit_postings
  WHERE transaction_id = checked_transaction_id;

  IF actual_count <> expected_count
     OR actual_total <> 0
     OR actual_assets <> 1
     OR EXISTS (
       SELECT 1
       FROM credit_postings
       WHERE transaction_id = checked_transaction_id
         AND asset_code <> expected_asset
     ) THEN
    RAISE EXCEPTION 'credit transaction % is not balanced for asset %', checked_transaction_id, expected_asset;
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;

CREATE CONSTRAINT TRIGGER validate_credit_transaction_on_insert
AFTER INSERT ON credit_transactions
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION validate_credit_transaction_balance();

CREATE OR REPLACE FUNCTION guard_credit_posting_transaction_scope()
RETURNS trigger AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM credit_transactions
    WHERE transaction_id = NEW.transaction_id
      AND xmin = pg_current_xact_id()::xid
  ) THEN
    RAISE EXCEPTION 'credit postings must be inserted in the transaction that created their ledger transaction';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER guard_credit_posting_transaction_scope
BEFORE INSERT ON credit_postings
FOR EACH ROW EXECUTE FUNCTION guard_credit_posting_transaction_scope();

