CREATE TABLE user_boards (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  board_id VARCHAR(100) NOT NULL,
  user_id BIGINT NOT NULL,
  name VARCHAR(60) NOT NULL,
  state TEXT NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uq_user_boards_user_board_id UNIQUE (user_id, board_id),
  CONSTRAINT uq_user_boards_board_id UNIQUE (board_id)
);

CREATE UNIQUE INDEX uq_user_board_name ON user_boards (user_id, lower(name));
CREATE INDEX idx_user_updated ON user_boards (user_id, updated_at);

CREATE TABLE board_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id BIGINT NOT NULL,
  board_id VARCHAR(100) NOT NULL,
  user_id BIGINT NOT NULL,
  role VARCHAR(20) NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uq_board_member UNIQUE (owner_user_id, board_id, user_id)
);

CREATE INDEX idx_board_member_user ON board_members (user_id, owner_user_id, board_id);

CREATE TABLE board_share_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  board_id VARCHAR(100) NOT NULL,
  token VARCHAR(128) NOT NULL,
  role VARCHAR(20) NOT NULL,
  created_by BIGINT NOT NULL,
  revoked BOOLEAN NOT NULL DEFAULT FALSE,
  expires_at TIMESTAMPTZ(3),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uq_board_share_tokens_token UNIQUE (token)
);

CREATE INDEX idx_board_share_token_board ON board_share_tokens (board_id, created_by, revoked, expires_at);
