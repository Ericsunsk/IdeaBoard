CREATE FUNCTION project_reward_code_counts()
RETURNS TRIGGER AS $$
DECLARE
  campaign_mode TEXT;
  should_decrement BOOLEAN;
BEGIN
  IF TG_OP = 'INSERT' THEN
    EXECUTE pg_catalog.format(
      'UPDATE %I.reward_campaigns SET issued_code_count = issued_code_count + 1, valid_unused_code_count = valid_unused_code_count + 1 WHERE id = $1',
      TG_TABLE_SCHEMA
    ) USING NEW.campaign_id;
    RETURN NEW;
  END IF;
  IF OLD.revoked_at IS NULL AND NEW.revoked_at IS NOT NULL THEN
    EXECUTE pg_catalog.format(
      'SELECT mode FROM %I.reward_campaigns WHERE id = $1', TG_TABLE_SCHEMA
    ) INTO campaign_mode USING NEW.campaign_id;
    IF campaign_mode = 'public' THEN
      should_decrement := TRUE;
    ELSE
      EXECUTE pg_catalog.format(
        'SELECT NOT EXISTS (SELECT 1 FROM %I.reward_redemptions WHERE code_id = $1)', TG_TABLE_SCHEMA
      ) INTO should_decrement USING NEW.id;
    END IF;
    IF should_decrement THEN
      EXECUTE pg_catalog.format(
        'UPDATE %I.reward_campaigns SET valid_unused_code_count = valid_unused_code_count - 1 WHERE id = $1',
        TG_TABLE_SCHEMA
      ) USING NEW.campaign_id;
    END IF;
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql SET search_path = pg_catalog;

