CREATE TABLE system_configs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  config_key VARCHAR(100) NOT NULL,
  value TEXT NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uq_system_configs_config_key UNIQUE (config_key)
);

CREATE TABLE storage_profiles (
  profile_id VARCHAR(64) PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  provider VARCHAR(50) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  is_current BOOLEAN NOT NULL DEFAULT FALSE,
  builtin BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(32) NOT NULL DEFAULT 'active',
  config JSONB NOT NULL DEFAULT '{}'::jsonb,
  created_by BIGINT,
  updated_by BIGINT,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  deleted_at TIMESTAMPTZ(3),
  CONSTRAINT ck_storage_profiles_provider CHECK (provider IN ('local', 's3-compatible')),
  CONSTRAINT ck_storage_profiles_status CHECK (status IN ('active', 'disabled', 'deleted')),
  CONSTRAINT ck_storage_profiles_config_object CHECK (jsonb_typeof(config) = 'object'),
  CONSTRAINT ck_storage_profiles_current_active CHECK (NOT is_current OR (enabled AND status = 'active' AND deleted_at IS NULL)),
  CONSTRAINT ck_storage_profiles_deleted_state CHECK (status <> 'deleted' OR (NOT enabled AND NOT is_current AND deleted_at IS NOT NULL)),
  CONSTRAINT ck_storage_profiles_deleted_at_state CHECK (deleted_at IS NULL OR status = 'deleted'),
  CONSTRAINT fk_storage_profiles_created_by FOREIGN KEY (created_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_storage_profiles_updated_by FOREIGN KEY (updated_by) REFERENCES users(id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX uq_storage_profiles_current ON storage_profiles (is_current) WHERE is_current;
CREATE INDEX idx_storage_profiles_provider_status ON storage_profiles (provider, status);

CREATE OR REPLACE FUNCTION safe_jsonb_object(raw TEXT)
RETURNS JSONB AS $$
DECLARE
  parsed JSONB;
BEGIN
  IF raw IS NULL OR btrim(raw) = '' THEN
    RETURN NULL;
  END IF;

  BEGIN
    parsed := raw::jsonb;
  EXCEPTION WHEN others THEN
    RETURN NULL;
  END;

  IF jsonb_typeof(parsed) = 'object' THEN
    RETURN parsed;
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql IMMUTABLE;

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TABLE storage_profile_secret_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id VARCHAR(64) NOT NULL,
  secret_name VARCHAR(64) NOT NULL,
  version_number INTEGER NOT NULL,
  secret_material_kind VARCHAR(20) NOT NULL DEFAULT 'encrypted',
  secret_ref TEXT NOT NULL DEFAULT '',
  secret_payload TEXT NOT NULL DEFAULT '',
  fingerprint VARCHAR(128) NOT NULL DEFAULT '',
  key_version VARCHAR(64) NOT NULL DEFAULT '',
  status VARCHAR(32) NOT NULL DEFAULT 'active',
  rotated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  expires_at TIMESTAMPTZ(3),
  retired_at TIMESTAMPTZ(3),
  revoked_at TIMESTAMPTZ(3),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT ck_storage_profile_secret_versions_version CHECK (version_number > 0),
  CONSTRAINT ck_storage_profile_secret_versions_material_kind CHECK (secret_material_kind IN ('encrypted', 'external_ref')),
  CONSTRAINT ck_storage_profile_secret_versions_status CHECK (status IN ('active', 'retired', 'revoked')),
  CONSTRAINT ck_storage_profile_secret_versions_material CHECK (
    status <> 'active'
    OR (secret_material_kind = 'encrypted' AND btrim(secret_payload) <> '')
    OR (secret_material_kind = 'external_ref' AND btrim(secret_ref) <> '')
  ),
  CONSTRAINT ck_storage_profile_secret_versions_timestamps CHECK (
    (status = 'active' AND retired_at IS NULL AND revoked_at IS NULL)
    OR (status = 'retired' AND retired_at IS NOT NULL AND revoked_at IS NULL)
    OR (status = 'revoked' AND revoked_at IS NOT NULL)
  ),
  CONSTRAINT uq_storage_profile_secret_versions_number UNIQUE (profile_id, secret_name, version_number),
  CONSTRAINT fk_storage_profile_secret_versions_profile_id FOREIGN KEY (profile_id) REFERENCES storage_profiles(profile_id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX uq_storage_profile_secret_versions_active ON storage_profile_secret_versions (profile_id, secret_name) WHERE status = 'active';
CREATE INDEX idx_storage_profile_secret_versions_status ON storage_profile_secret_versions (status, expires_at);



-- Canonical objects introduced by the clean-break baseline.
-- Name: get_auth_runtime_settings(); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION get_auth_runtime_settings() RETURNS TABLE(registration_enabled boolean)
    LANGUAGE plpgsql STABLE SECURITY DEFINER
    SET search_path TO 'public', 'pg_catalog', 'pg_temp'
    AS $$
BEGIN
  RETURN QUERY
  SELECT COALESCE(
      (
        SELECT lower(btrim(config.value)) = 'true'
        FROM system_configs AS config
        WHERE config.config_key = 'auth_registration_enabled'
        LIMIT 1
      ),
      FALSE
    );
END;
$$;


