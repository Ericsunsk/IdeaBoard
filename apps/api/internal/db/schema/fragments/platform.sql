-- Canonical objects introduced by the clean-break baseline.
-- Name: get_auth_runtime_settings(); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION get_auth_runtime_settings() RETURNS TABLE(
  registration_enabled boolean,
  branding_project_name text,
  branding_logo_url text
)
    LANGUAGE plpgsql STABLE SECURITY DEFINER
    SET search_path TO 'public', 'pg_catalog', 'pg_temp'
    AS $$
BEGIN
  RETURN QUERY
  SELECT
    COALESCE(
      (
        SELECT lower(btrim(config.value)) = 'true'
        FROM system_configs AS config
        WHERE config.config_key = 'auth_registration_enabled'
        LIMIT 1
      ),
      FALSE
    ),
    COALESCE(
      (
        SELECT btrim(config.value)
        FROM system_configs AS config
        WHERE config.config_key = 'branding_project_name'
        LIMIT 1
      ),
      'IdeaBoard'
    ),
    COALESCE(
      (
        SELECT btrim(config.value)
        FROM system_configs AS config
        WHERE config.config_key = 'branding_logo_url'
        LIMIT 1
      ),
      ''
    );
END;
$$;

-- Auth login-lockout budgets for the guard-settings reader. Additive:
-- get_auth_runtime_settings() stays frozen because changing its return
-- table would require DROP + CREATE (blocked by the destructive gate),
-- so lockout travels in its own SECURITY DEFINER seam with the same
-- search_path discipline. Bounds live in readers, not here.
CREATE FUNCTION get_auth_login_lockout_settings() RETURNS TABLE(
  login_lockout_threshold integer,
  login_lockout_duration_seconds integer
)
    LANGUAGE plpgsql STABLE SECURITY DEFINER
    SET search_path TO 'public', 'pg_catalog', 'pg_temp'
    AS $$
BEGIN
  RETURN QUERY
  SELECT
    COALESCE(
      (
        SELECT
          CASE
            WHEN btrim(config.value) ~ '^[0-9]+$' THEN btrim(config.value)::integer
            ELSE NULL
          END
        FROM system_configs AS config
        WHERE config.config_key = 'auth_login_lockout_threshold'
        LIMIT 1
      ),
      10
    ),
    COALESCE(
      (
        SELECT
          CASE
            WHEN btrim(config.value) ~ '^[0-9]+$' THEN btrim(config.value)::integer
            ELSE NULL
          END
        FROM system_configs AS config
        WHERE config.config_key = 'auth_login_lockout_duration_seconds'
        LIMIT 1
      ),
      900
    );
END;
$$;

REVOKE ALL ON FUNCTION get_auth_login_lockout_settings() FROM PUBLIC;

-- Bind the new privileged routine to the installed schema, mirroring the
-- bootstrap hardening block: every SECURITY DEFINER routine resolves
-- tables through the installing schema first. The baseline-era generic
-- block only covers routines that existed at baseline time, so post
-- baseline routines carry their own binding (see identity.sql).
DO $$
DECLARE trusted_schema TEXT := current_schema();
BEGIN
  EXECUTE format(
    'ALTER FUNCTION %I.get_auth_login_lockout_settings() SET search_path TO %I, pg_catalog, pg_temp',
    trusted_schema, trusted_schema
  );
END;
$$;


