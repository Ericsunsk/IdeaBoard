-- Identity admin reconciliation (dry-run alerting only).
--
-- The admin commands in internal/identity/users/application/administration
-- apply Auth-then-local without an automatic convergence mechanism, so a
-- crash between the two writes (or a partially compensating rollback)
-- leaves local users rows and Better Auth identities diverged. These tables
-- record periodic dry-run scans: each run compares the local users rows
-- against the Auth read-only batch endpoint and stores one finding per
-- drift. Automatic remediation is intentionally absent in this phase; the
-- scan only writes runs/findings rows and emits slog alerts.
--
-- Known gap (alert-only, never repaired): the local users row has no
-- ban_reason/ban_expires columns, so Auth-side ban metadata cannot be
-- compared against local intent. Mismatch findings record the Auth-side
-- metadata in details for operator review. Sessions are excluded from
-- reconciliation: a deleted Auth session is unrecoverable, so there is no
-- converged state to restore.

CREATE TABLE identity_admin_reconciliation_runs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status VARCHAR(16) NOT NULL DEFAULT 'queued',
  trigger_type VARCHAR(16) NOT NULL,
  requested_by BIGINT,
  reason VARCHAR(1000),
  scheduled_for TIMESTAMPTZ(3),
  finding_count BIGINT NOT NULL DEFAULT 0 CHECK (finding_count >= 0),
  attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
  error_message TEXT NOT NULL DEFAULT '',
  requested_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  started_at TIMESTAMPTZ(3),
  completed_at TIMESTAMPTZ(3),
  CONSTRAINT ck_identity_admin_recon_run_trigger CHECK (trigger_type IN ('manual', 'scheduled')),
  CONSTRAINT ck_identity_admin_recon_run_audit CHECK (
    (
      trigger_type = 'manual'
      AND requested_by IS NOT NULL
      AND requested_by > 0
      AND reason IS NOT NULL
      AND reason = btrim(reason, E' \t\n\r\f')
      AND char_length(reason) BETWEEN 1 AND 1000
      AND scheduled_for IS NULL
    )
    OR
    (
      trigger_type = 'scheduled'
      AND requested_by IS NULL
      AND reason IS NULL
      AND scheduled_for IS NOT NULL
    )
  ),
  CONSTRAINT ck_identity_admin_recon_run_status CHECK (status IN ('queued', 'running', 'completed', 'failed')),
  CONSTRAINT ck_identity_admin_recon_run_timestamps CHECK (
    (status = 'queued' AND completed_at IS NULL)
    OR (status = 'running' AND started_at IS NOT NULL AND completed_at IS NULL)
    OR (status IN ('completed', 'failed') AND started_at IS NOT NULL AND completed_at IS NOT NULL)
  )
);

CREATE UNIQUE INDEX uq_identity_admin_recon_active_run
  ON identity_admin_reconciliation_runs ((TRUE)) WHERE status IN ('queued', 'running');
CREATE UNIQUE INDEX uq_identity_admin_recon_scheduled_for
  ON identity_admin_reconciliation_runs (scheduled_for) WHERE trigger_type = 'scheduled';
CREATE INDEX idx_identity_admin_recon_runs_requested_at
  ON identity_admin_reconciliation_runs (id DESC);

CREATE TABLE identity_admin_reconciliation_findings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fingerprint CHAR(64) NOT NULL UNIQUE CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
  finding_type VARCHAR(64) NOT NULL,
  severity VARCHAR(16) NOT NULL,
  risk VARCHAR(16) NOT NULL,
  user_id BIGINT REFERENCES users(id) ON UPDATE RESTRICT ON DELETE SET NULL,
  subject_type VARCHAR(32) NOT NULL,
  subject_id VARCHAR(160) NOT NULL,
  details JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(details) = 'object'),
  status VARCHAR(16) NOT NULL DEFAULT 'open',
  first_seen_run_id BIGINT NOT NULL REFERENCES identity_admin_reconciliation_runs(id) ON DELETE RESTRICT,
  last_seen_run_id BIGINT NOT NULL REFERENCES identity_admin_reconciliation_runs(id) ON DELETE RESTRICT,
  occurrence_count BIGINT NOT NULL DEFAULT 1 CHECK (occurrence_count > 0),
  first_seen_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  last_seen_at TIMESTAMPTZ(3) NOT NULL DEFAULT clock_timestamp(),
  resolved_at TIMESTAMPTZ(3),
  CONSTRAINT ck_identity_admin_recon_finding_severity CHECK (severity IN ('warning', 'error', 'critical')),
  CONSTRAINT ck_identity_admin_recon_finding_risk CHECK (risk IN ('low', 'high')),
  CONSTRAINT ck_identity_admin_recon_finding_status CHECK (status IN ('open', 'resolved')),
  CONSTRAINT ck_identity_admin_recon_finding_resolution CHECK (
    (status = 'open' AND resolved_at IS NULL) OR (status = 'resolved' AND resolved_at IS NOT NULL)
  )
);

CREATE INDEX idx_identity_admin_recon_findings_list
  ON identity_admin_reconciliation_findings (status, id DESC);
