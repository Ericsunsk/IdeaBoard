  PRIMARY KEY (run_id, finding_id)
);

CREATE FUNCTION start_identity_admin_reconciliation(
  p_trigger_type TEXT,
  p_requested_by BIGINT,
  p_reason TEXT,
  p_scheduled_for TIMESTAMPTZ,
  p_only_if_overdue BOOLEAN
)
RETURNS TABLE (run_id BIGINT, enqueue_required BOOLEAN) AS $$
DECLARE
  v_run_id BIGINT;
  v_run_status VARCHAR(16);
BEGIN
  p_trigger_type := btrim(p_trigger_type);
  p_reason := NULLIF(btrim(p_reason, E' \t\n\r\f'), '');
  IF p_trigger_type IS NULL
     OR p_only_if_overdue IS NULL
     OR (
       p_trigger_type = 'manual'
       AND (
         p_requested_by IS NULL OR p_requested_by <= 0
         OR p_reason IS NULL OR char_length(p_reason) > 1000
         OR p_scheduled_for IS NOT NULL
         OR p_only_if_overdue
       )
     )
     OR (
       p_trigger_type = 'scheduled'
       AND (
         p_requested_by IS NOT NULL
         OR p_reason IS NOT NULL
         OR p_scheduled_for IS NULL
       )
     )
     OR p_trigger_type NOT IN ('manual', 'scheduled') THEN
    RAISE EXCEPTION USING ERRCODE = 'IB311', MESSAGE = 'invalid identity admin reconciliation request';
  END IF;

  PERFORM pg_advisory_xact_lock(5283921922134398291);

  IF p_only_if_overdue AND EXISTS (
    SELECT 1
    FROM identity_admin_reconciliation_runs
    WHERE status = 'completed'
      AND completed_at >= clock_timestamp() - INTERVAL '24 hours'
  ) THEN
    RETURN QUERY SELECT NULL::BIGINT, FALSE;
    RETURN;
  END IF;

  SELECT runs.id INTO v_run_id
  FROM identity_admin_reconciliation_runs runs
  WHERE runs.status IN ('queued', 'running')
  ORDER BY runs.id DESC
  LIMIT 1;
  IF FOUND THEN
    RETURN QUERY SELECT v_run_id, FALSE;
    RETURN;
  END IF;

  IF p_trigger_type = 'scheduled' THEN
    SELECT runs.id, runs.status INTO v_run_id, v_run_status
    FROM identity_admin_reconciliation_runs runs
    WHERE runs.trigger_type = 'scheduled'
      AND runs.scheduled_for = p_scheduled_for;
    IF FOUND THEN
      IF p_only_if_overdue AND v_run_status = 'failed' THEN
        UPDATE identity_admin_reconciliation_runs
        SET status = 'queued',
            error_message = '',
            started_at = NULL,
            completed_at = NULL
        WHERE id = v_run_id;
        RETURN QUERY SELECT v_run_id, TRUE;
        RETURN;
      END IF;
      RETURN QUERY SELECT v_run_id, FALSE;
      RETURN;
    END IF;
  END IF;

  INSERT INTO identity_admin_reconciliation_runs (
    trigger_type,
    requested_by,
    reason,
    scheduled_for
  )
  VALUES (
    p_trigger_type,
    p_requested_by,
    p_reason,
    p_scheduled_for
  )
  RETURNING id INTO v_run_id;

  RETURN QUERY SELECT v_run_id, TRUE;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog;

CREATE FUNCTION fail_identity_admin_reconciliation(p_run_id BIGINT, p_error TEXT)
RETURNS VOID AS $$
BEGIN
  UPDATE identity_admin_reconciliation_runs
  SET status = 'failed', started_at = COALESCE(started_at, clock_timestamp()), completed_at = clock_timestamp(),
      error_message = left(COALESCE(p_error, ''), 2000)
  WHERE id = p_run_id AND status IN ('queued', 'running');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog;

REVOKE ALL ON FUNCTION start_identity_admin_reconciliation(TEXT, BIGINT, TEXT, TIMESTAMPTZ, BOOLEAN) FROM PUBLIC;
REVOKE ALL ON FUNCTION fail_identity_admin_reconciliation(BIGINT, TEXT) FROM PUBLIC;

-- Bind the new privileged routines to the installed schema, mirroring the
-- bootstrap hardening block: every SECURITY DEFINER routine resolves
-- tables through the installing schema first.
DO $$
DECLARE trusted_schema TEXT := current_schema();
BEGIN
  EXECUTE format(
    'ALTER FUNCTION %I.start_identity_admin_reconciliation(TEXT, BIGINT, TEXT, TIMESTAMPTZ, BOOLEAN) SET search_path TO %I, pg_catalog, pg_temp',
    trusted_schema, trusted_schema
  );
  EXECUTE format(
    'ALTER FUNCTION %I.fail_identity_admin_reconciliation(BIGINT, TEXT) SET search_path TO %I, pg_catalog, pg_temp',
    trusted_schema, trusted_schema
  );
END;
$$;

-- Durable Auth sync intents (issue #888): business authorization state
-- (users.role/status) is the fact source; every lane Role/Ban/Unban
-- mutation persists one intent row in the SAME transaction as the
-- business write (and the control audit row on the guarded path). External
-- Auth I/O only ever runs after that transaction commits, from the
-- desired snapshot stored here. A dedicated sweep converges pending
-- intents with per-user serialization and version fencing, so database
-- errors, Auth errors, or a process crash between commit and push all
-- converge by retry instead of stranding divergence.
CREATE TABLE identity_auth_sync_intents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  auth_user_id VARCHAR(128) NOT NULL,
  op VARCHAR(16) NOT NULL,
  desired_role VARCHAR(20) NOT NULL,
  desired_banned BOOLEAN NOT NULL,
  reason TEXT NOT NULL DEFAULT '',
  expires_in_seconds INTEGER NOT NULL DEFAULT 0 CHECK (expires_in_seconds >= 0),
  base_version BIGINT NOT NULL CHECK (base_version >= 0),
  status VARCHAR(16) NOT NULL DEFAULT 'pending',
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),
  last_error TEXT NOT NULL DEFAULT '',
  next_attempt_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  claimed_at TIMESTAMPTZ(3),
  completed_at TIMESTAMPTZ(3),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT ck_identity_auth_sync_intents_op CHECK (op IN ('role', 'ban', 'unban')),
  CONSTRAINT ck_identity_auth_sync_intents_role CHECK (desired_role IN ('admin', 'user')),
  CONSTRAINT ck_identity_auth_sync_intents_status CHECK (status IN ('pending', 'in_flight', 'done', 'superseded', 'failed')),
  CONSTRAINT ck_identity_auth_sync_intents_claim CHECK (
    (status = 'in_flight' AND claimed_at IS NOT NULL)
    OR (status <> 'in_flight')
  ),
  CONSTRAINT ck_identity_auth_sync_intents_completion CHECK (
    (status IN ('done', 'superseded', 'failed') AND completed_at IS NOT NULL)
    OR (status IN ('pending', 'in_flight') AND completed_at IS NULL)
  )
);

-- The sweep claims due intents oldest-first without scanning terminal rows.
CREATE INDEX idx_identity_auth_sync_intents_due
  ON identity_auth_sync_intents (status, next_attempt_at, id)
  WHERE status IN ('pending', 'in_flight');
-- Per-user history for operators and for the supersede check.
CREATE INDEX idx_identity_auth_sync_intents_user
  ON identity_auth_sync_intents (user_id, id DESC);

-- Ban expiry sweep index (issue #895): due finite bans only. Permanent
-- bans (NULL deadline) and active users never match.
CREATE INDEX idx_users_ban_expiry_sweep
  ON users (ban_expires_at, id)
  WHERE status = 0 AND ban_expires_at IS NOT NULL;
