CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL DEFAULT gen_random_uuid(),
  display_name VARCHAR(100) NOT NULL DEFAULT 'IdeaBoard User',
  auth_user_id VARCHAR(128),
  storage_uid CHAR(6) NOT NULL,
  avatar VARCHAR(1024) NOT NULL DEFAULT '',
  role VARCHAR(20) NOT NULL DEFAULT 'user',
  status SMALLINT NOT NULL DEFAULT 1,
  last_login_ip VARCHAR(45),
  last_login_country VARCHAR(2),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  -- Durable Auth sync (issue #888): monotonic version fencing for the
  -- business authorization facts (role/status). Every lane mutation that
  -- changes role/status bumps this counter in the same transaction that
  -- persists the Auth sync intent; the sync worker only pushes an intent
  -- whose base_version still matches, so a stale intent can never
  -- overwrite a newer business state.
  auth_sync_version BIGINT NOT NULL DEFAULT 0 CHECK (auth_sync_version >= 0),
  -- Ban deadline fact source (issue #895): NULL means a permanent ban
  -- that never expires. Finite bans converge to unban through the expiry
  -- sweep, which flips status + Wallet and persists an unban intent in
  -- one transaction.
  ban_expires_at TIMESTAMPTZ(3) NULL,
  CONSTRAINT uq_users_public_id UNIQUE (public_id),
  CONSTRAINT uq_users_auth_user_id UNIQUE (auth_user_id),
  CONSTRAINT uq_users_storage_uid UNIQUE (storage_uid),
  CONSTRAINT chk_users_role CHECK (role IN ('admin', 'user')),
  CONSTRAINT chk_users_display_name CHECK (length(btrim(display_name)) BETWEEN 1 AND 100),
  CONSTRAINT chk_users_status CHECK (status IN (0, 1)),
  CONSTRAINT chk_users_last_login_ip CHECK (last_login_ip IS NULL OR last_login_ip <> ''),
  CONSTRAINT chk_users_last_login_country CHECK (last_login_country IS NULL OR last_login_country ~ '^[A-Z]{2}$'),
  CONSTRAINT chk_users_storage_uid CHECK (storage_uid ~ '^[A-Z0-9]{6}$')
);

CREATE TABLE users_used_uids (
