CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL DEFAULT gen_random_uuid(),
  display_name VARCHAR(100) NOT NULL DEFAULT 'IdeaBoard User',
  auth_user_id VARCHAR(128),
  storage_uid CHAR(6) NOT NULL,
  avatar VARCHAR(1024) NOT NULL DEFAULT '',
  role VARCHAR(20) NOT NULL DEFAULT 'user',
  status SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uq_users_public_id UNIQUE (public_id),
  CONSTRAINT uq_users_auth_user_id UNIQUE (auth_user_id),
  CONSTRAINT uq_users_storage_uid UNIQUE (storage_uid),
  CONSTRAINT chk_users_role CHECK (role IN ('admin', 'user')),
  CONSTRAINT chk_users_display_name CHECK (length(btrim(display_name)) BETWEEN 1 AND 100),
  CONSTRAINT chk_users_status CHECK (status IN (0, 1)),
  CONSTRAINT chk_users_storage_uid CHECK (storage_uid ~ '^[A-Z0-9]{6}$')
);

CREATE TABLE users_used_uids (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  storage_uid CHAR(6) NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uq_users_used_uids_storage_uid UNIQUE (storage_uid),
  CONSTRAINT chk_users_used_uids_storage_uid CHECK (storage_uid ~ '^[A-Z0-9]{6}$')
);



