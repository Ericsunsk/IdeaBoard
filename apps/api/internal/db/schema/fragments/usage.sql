CREATE TABLE task_daily_stats (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stat_date DATE NOT NULL,
  user_id BIGINT NOT NULL DEFAULT 0,
  account_id BIGINT NOT NULL DEFAULT 0,
  provider_endpoint_id BIGINT NOT NULL DEFAULT 0,
  credential_id BIGINT NOT NULL DEFAULT 0,
  feature_slug VARCHAR(64) NOT NULL DEFAULT '',
  api_type VARCHAR(50) NOT NULL DEFAULT '',
  model_name VARCHAR(128) NOT NULL DEFAULT '',
  user_key VARCHAR(128) NOT NULL DEFAULT '',
  total BIGINT NOT NULL DEFAULT 0,
  completed BIGINT NOT NULL DEFAULT 0,
  failed BIGINT NOT NULL DEFAULT 0,
  cancelled BIGINT NOT NULL DEFAULT 0,
  latency_seconds_sum DOUBLE PRECISION NOT NULL DEFAULT 0,
  latency_count BIGINT NOT NULL DEFAULT 0,
  cost_micros_sum BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uq_task_daily_stat UNIQUE (
    stat_date, user_id, account_id, provider_endpoint_id, credential_id, feature_slug, api_type, model_name, user_key
  ),
  CONSTRAINT chk_task_daily_stats_counts CHECK (
    total >= 0
    AND completed >= 0
    AND failed >= 0
    AND cancelled >= 0
    AND total = completed + failed + cancelled
    AND latency_seconds_sum >= 0
    AND latency_count >= 0
    AND latency_count <= completed
    AND cost_micros_sum >= 0
  ),
  CONSTRAINT chk_task_daily_stats_dimension_ids CHECK (user_id >= 0 AND account_id >= 0 AND provider_endpoint_id >= 0 AND credential_id >= 0)
);

CREATE TABLE task_stat_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id VARCHAR(64) NOT NULL,
  occurred_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  stat_date DATE NOT NULL,
  user_id BIGINT NOT NULL DEFAULT 0,
  account_id BIGINT NOT NULL DEFAULT 0,
  provider_endpoint_id BIGINT NOT NULL DEFAULT 0,
  credential_id BIGINT NOT NULL DEFAULT 0,
  feature_slug VARCHAR(64) NOT NULL DEFAULT '',
  api_type VARCHAR(50) NOT NULL DEFAULT '',
  model_name VARCHAR(128) NOT NULL DEFAULT '',
  user_key VARCHAR(128) NOT NULL DEFAULT '',
  status VARCHAR(20) NOT NULL,
  latency_seconds DOUBLE PRECISION NOT NULL DEFAULT 0,
  cost_micros BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uq_task_stat_event_task_id UNIQUE (task_id),
  CONSTRAINT chk_task_stat_events_status CHECK (status IN ('completed', 'failed', 'cancelled')),
  CONSTRAINT chk_task_stat_events_latency CHECK (latency_seconds >= 0),
  CONSTRAINT chk_task_stat_events_cost CHECK (cost_micros >= 0),
  CONSTRAINT chk_task_stat_events_dimension_ids CHECK (user_id >= 0 AND account_id >= 0 AND provider_endpoint_id >= 0 AND credential_id >= 0)
);

CREATE INDEX idx_task_stat_events_stat_date ON task_stat_events (stat_date);
CREATE INDEX idx_task_stat_events_occurred_at ON task_stat_events (occurred_at);
CREATE INDEX idx_task_stat_events_model_latency ON task_stat_events (stat_date, model_name, latency_seconds) WHERE latency_seconds > 0;
CREATE INDEX idx_task_stat_events_account_date ON task_stat_events (account_id, stat_date) WHERE account_id > 0;
CREATE INDEX idx_task_stat_events_provider_endpoint_date ON task_stat_events (provider_endpoint_id, stat_date) WHERE provider_endpoint_id > 0;
CREATE INDEX idx_task_stat_events_credential_date ON task_stat_events (credential_id, stat_date) WHERE credential_id > 0;
CREATE INDEX idx_task_stat_events_feature_api_date ON task_stat_events (stat_date, feature_slug, api_type);

CREATE TABLE task_daily_stat_backfills (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  stat_date DATE NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT uq_task_daily_stat_backfill_date UNIQUE (stat_date)
);
