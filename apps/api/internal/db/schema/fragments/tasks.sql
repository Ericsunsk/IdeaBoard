CREATE TABLE tasks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id VARCHAR(64) NOT NULL,
  user_id BIGINT NOT NULL,
  client_action_id VARCHAR(128) NOT NULL DEFAULT '',
  assigned_provider_endpoint_id BIGINT,
  assigned_credential_id BIGINT,
  account_id BIGINT,
  prompt TEXT NOT NULL,
  user_prompt TEXT NOT NULL,
  params TEXT NOT NULL,
  feature_slug VARCHAR(64) NOT NULL DEFAULT '',
  priority INTEGER NOT NULL DEFAULT 2,
  status VARCHAR(20) NOT NULL DEFAULT 'pending',
  lease_token VARCHAR(128) NOT NULL DEFAULT '',
  retry_count INTEGER NOT NULL DEFAULT 0,
  attempt_seq INTEGER NOT NULL DEFAULT 0,
  error_msg TEXT NOT NULL,
  result TEXT NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  completed_at TIMESTAMPTZ(3),
  cancelled_at TIMESTAMPTZ(3),
  cancelled_by BIGINT,
  cancel_reason TEXT NOT NULL DEFAULT '',
  CONSTRAINT uq_tasks_task_id UNIQUE (task_id),
  CONSTRAINT ck_tasks_client_action_id_trimmed CHECK (client_action_id = btrim(client_action_id)),
  CONSTRAINT ck_tasks_status CHECK (status IN ('pending', 'running', 'completed', 'failed', 'cancelled')),
  CONSTRAINT ck_tasks_priority CHECK (priority BETWEEN 1 AND 4),
  CONSTRAINT ck_tasks_retry_count_non_negative CHECK (retry_count >= 0),
  CONSTRAINT ck_tasks_attempt_seq_non_negative CHECK (attempt_seq >= 0),
  CONSTRAINT ck_tasks_assignment_pair CHECK (
    (account_id IS NULL AND assigned_provider_endpoint_id IS NULL AND assigned_credential_id IS NULL)
    OR (account_id IS NOT NULL AND assigned_provider_endpoint_id IS NOT NULL AND assigned_credential_id IS NOT NULL)
  ),
  CONSTRAINT ck_tasks_assignment_status CHECK (
    (status = 'pending' AND account_id IS NULL AND assigned_provider_endpoint_id IS NULL AND assigned_credential_id IS NULL)
    OR (status = 'running' AND account_id IS NOT NULL AND assigned_provider_endpoint_id IS NOT NULL AND assigned_credential_id IS NOT NULL)
    OR status IN ('completed', 'failed', 'cancelled')
  ),
  CONSTRAINT ck_tasks_lease_status CHECK (status = 'running' OR lease_token = ''),
  CONSTRAINT ck_tasks_terminal_consistency CHECK (
    (
      status IN ('pending', 'running')
      AND completed_at IS NULL
      AND cancelled_at IS NULL
      AND cancelled_by IS NULL
      AND cancel_reason = ''
    )
    OR (
      status = 'completed'
      AND completed_at IS NOT NULL
      AND cancelled_at IS NULL
      AND cancelled_by IS NULL
      AND cancel_reason = ''
    )
    OR (
      status = 'failed'
      AND completed_at IS NOT NULL
      AND cancelled_at IS NULL
      AND cancelled_by IS NULL
      AND cancel_reason = ''
      AND btrim(error_msg) <> ''
    )
    OR (
      status = 'cancelled'
      AND completed_at IS NOT NULL
      AND cancelled_at IS NOT NULL
      AND btrim(cancel_reason) <> ''
    )
  ),
  CONSTRAINT ck_tasks_assigned_provider_endpoint_id_positive CHECK (assigned_provider_endpoint_id IS NULL OR assigned_provider_endpoint_id > 0),
  CONSTRAINT ck_tasks_assigned_credential_id_positive CHECK (assigned_credential_id IS NULL OR assigned_credential_id > 0),
  CONSTRAINT ck_tasks_account_id_positive CHECK (account_id IS NULL OR account_id > 0),
  CONSTRAINT ck_tasks_cancelled_by_positive CHECK (cancelled_by IS NULL OR cancelled_by > 0),
  CONSTRAINT fk_tasks_user_id FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_tasks_account_id FOREIGN KEY (account_id) REFERENCES api_accounts(id) ON DELETE RESTRICT,
  CONSTRAINT fk_tasks_assigned_credential_id FOREIGN KEY (assigned_credential_id) REFERENCES api_account_secrets(id) ON DELETE RESTRICT,
  CONSTRAINT fk_tasks_account_credential FOREIGN KEY (assigned_credential_id, account_id) REFERENCES api_account_secrets(id, account_id) ON DELETE RESTRICT,
  CONSTRAINT fk_tasks_cancelled_by FOREIGN KEY (cancelled_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_tasks_assigned_provider_endpoint_id FOREIGN KEY (assigned_provider_endpoint_id) REFERENCES provider_endpoints(id) ON DELETE RESTRICT,
  CONSTRAINT fk_tasks_account_provider_endpoint FOREIGN KEY (account_id, assigned_provider_endpoint_id) REFERENCES api_accounts(id, provider_endpoint_id) ON DELETE RESTRICT
);

CREATE INDEX idx_tasks_user_id ON tasks (user_id);
CREATE UNIQUE INDEX uq_tasks_user_client_action_id ON tasks (user_id, client_action_id) WHERE client_action_id <> '';
CREATE INDEX idx_tasks_account_id ON tasks (account_id) WHERE account_id IS NOT NULL;
CREATE INDEX idx_tasks_assigned_credential_id ON tasks (assigned_credential_id) WHERE assigned_credential_id IS NOT NULL;
CREATE INDEX idx_tasks_status ON tasks (status);
CREATE INDEX idx_tasks_lease_token ON tasks (lease_token);
CREATE INDEX idx_tasks_created_at ON tasks (created_at);
CREATE INDEX idx_tasks_running_account ON tasks (account_id) WHERE status = 'running' AND account_id IS NOT NULL;
CREATE INDEX idx_tasks_user_created_at ON tasks (user_id, created_at DESC);
CREATE INDEX idx_tasks_status_created_at ON tasks (status, created_at DESC);
CREATE INDEX idx_tasks_account_status_created_at ON tasks (account_id, status, created_at DESC) WHERE account_id IS NOT NULL;
CREATE INDEX idx_tasks_assigned_provider_endpoint_created_at ON tasks (assigned_provider_endpoint_id, created_at DESC) WHERE assigned_provider_endpoint_id IS NOT NULL;
CREATE INDEX idx_tasks_feature_created_at ON tasks (feature_slug, created_at DESC) WHERE feature_slug <> '';
CREATE INDEX idx_tasks_terminal_created_at ON tasks (created_at) WHERE status IN ('completed', 'failed', 'cancelled');
CREATE INDEX idx_tasks_pending_updated_at ON tasks (updated_at) WHERE status = 'pending';

CREATE TABLE task_execution_metrics (
  task_id VARCHAR(64) PRIMARY KEY,
  current_stage VARCHAR(32) NOT NULL DEFAULT 'queued',
  bottleneck_source VARCHAR(32) NOT NULL DEFAULT 'unknown',
  failure_stage VARCHAR(32) NOT NULL DEFAULT '',
  failure_category VARCHAR(64) NOT NULL DEFAULT '',
  assigned_at TIMESTAMPTZ(3),
  provider_started_at TIMESTAMPTZ(3),
  provider_finished_at TIMESTAMPTZ(3),
  finalize_started_at TIMESTAMPTZ(3),
  finalize_finished_at TIMESTAMPTZ(3),
  queue_wait_ms BIGINT NOT NULL DEFAULT 0,
  worker_overhead_ms BIGINT NOT NULL DEFAULT 0,
  provider_latency_ms BIGINT NOT NULL DEFAULT 0,
  finalize_latency_ms BIGINT NOT NULL DEFAULT 0,
  total_latency_ms BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT fk_task_execution_metrics_task_id FOREIGN KEY (task_id) REFERENCES tasks(task_id) ON DELETE CASCADE,
  CONSTRAINT ck_task_execution_metrics_current_stage CHECK (current_stage IN ('queued', 'assigned', 'provider', 'finalizing', 'completed', 'failed', 'cancelled')),
  CONSTRAINT ck_task_execution_metrics_bottleneck_source CHECK (bottleneck_source IN ('queue', 'worker', 'provider', 'storage', 'finalize', 'input', 'unknown')),
  CONSTRAINT ck_task_execution_metrics_terminal_consistency CHECK (
    (current_stage = 'completed' AND failure_stage = '' AND failure_category = '')
    OR (current_stage = 'failed' AND btrim(failure_stage) <> '' AND btrim(failure_category) <> '')
    OR (current_stage = 'cancelled' AND btrim(failure_stage) <> '' AND failure_category = 'cancelled')
    OR current_stage IN ('queued', 'assigned', 'provider', 'finalizing')
  ),
  CONSTRAINT ck_task_execution_metrics_latency_non_negative CHECK (
    queue_wait_ms >= 0
    AND worker_overhead_ms >= 0
    AND provider_latency_ms >= 0
    AND finalize_latency_ms >= 0
    AND total_latency_ms >= 0
  )
);

CREATE INDEX idx_task_execution_metrics_current_stage ON task_execution_metrics (current_stage);
CREATE INDEX idx_task_execution_metrics_bottleneck_source ON task_execution_metrics (bottleneck_source);
CREATE INDEX idx_task_execution_metrics_failure_category ON task_execution_metrics (failure_category);

CREATE TABLE task_leases (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id VARCHAR(64) NOT NULL,
  lease_token VARCHAR(128) NOT NULL,
  river_job_id BIGINT NOT NULL DEFAULT 0,
  account_id BIGINT NOT NULL,
  provider_endpoint_id BIGINT NOT NULL,
  credential_id BIGINT NOT NULL,
  feature_slug VARCHAR(64) NOT NULL DEFAULT '',
  resolved_model VARCHAR(128) NOT NULL DEFAULT '',
  api_type VARCHAR(50) NOT NULL DEFAULT '',
  provider_endpoint_name VARCHAR(100) NOT NULL DEFAULT '',
  provider_endpoint_base_url VARCHAR(500) NOT NULL DEFAULT '',
  credential_fingerprint VARCHAR(128) NOT NULL DEFAULT '',
  credential_key_version VARCHAR(64) NOT NULL DEFAULT '',
  acquired_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  released_at TIMESTAMPTZ(3),
  release_reason VARCHAR(32) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT fk_task_leases_task_id FOREIGN KEY (task_id) REFERENCES tasks(task_id) ON DELETE CASCADE,
  CONSTRAINT ck_task_leases_ids_valid CHECK (river_job_id >= 0 AND account_id > 0 AND provider_endpoint_id > 0 AND credential_id > 0),
  CONSTRAINT ck_task_leases_snapshot CHECK (
    btrim(lease_token) <> ''
    AND btrim(resolved_model) <> ''
    AND btrim(api_type) <> ''
    AND btrim(provider_endpoint_base_url) <> ''
  ),
  CONSTRAINT ck_task_leases_release_reason CHECK (
    (released_at IS NULL AND release_reason = '')
    OR (released_at IS NOT NULL AND release_reason IN ('completed', 'failed', 'requeued', 'cancelled', 'reset', 'account_failed'))
  ),
  CONSTRAINT fk_task_leases_account_id FOREIGN KEY (account_id) REFERENCES api_accounts(id) ON DELETE RESTRICT,
  CONSTRAINT fk_task_leases_provider_endpoint_id FOREIGN KEY (provider_endpoint_id) REFERENCES provider_endpoints(id) ON DELETE RESTRICT,
  CONSTRAINT fk_task_leases_credential_id FOREIGN KEY (credential_id) REFERENCES api_account_secrets(id) ON DELETE RESTRICT,
  CONSTRAINT fk_task_leases_account_credential FOREIGN KEY (credential_id, account_id) REFERENCES api_account_secrets(id, account_id) ON DELETE RESTRICT,
  CONSTRAINT fk_task_leases_account_provider_endpoint FOREIGN KEY (account_id, provider_endpoint_id) REFERENCES api_accounts(id, provider_endpoint_id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_task_leases_task_active ON task_leases (task_id) WHERE released_at IS NULL;
CREATE UNIQUE INDEX uq_task_leases_lease_token ON task_leases (lease_token);
CREATE INDEX idx_task_leases_active_account ON task_leases (account_id, task_id) WHERE released_at IS NULL;
CREATE INDEX idx_task_leases_active_model ON task_leases (account_id, lower(resolved_model)) WHERE released_at IS NULL;
CREATE INDEX idx_task_leases_credential_created_at ON task_leases (credential_id, created_at DESC);
CREATE INDEX idx_task_leases_released_at ON task_leases (released_at DESC) WHERE released_at IS NOT NULL;

CREATE TABLE task_attempts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  task_id VARCHAR(64) NOT NULL,
  lease_id BIGINT NOT NULL,
  attempt_no INTEGER NOT NULL,
  river_job_id BIGINT NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'running',
  failure_stage VARCHAR(32) NOT NULL DEFAULT '',
  failure_category VARCHAR(64) NOT NULL DEFAULT '',
  error_msg TEXT NOT NULL DEFAULT '',
  provider_started_at TIMESTAMPTZ(3),
  provider_finished_at TIMESTAMPTZ(3),
  finalize_started_at TIMESTAMPTZ(3),
  finalize_finished_at TIMESTAMPTZ(3),
  provider_latency_ms BIGINT NOT NULL DEFAULT 0,
  finalize_latency_ms BIGINT NOT NULL DEFAULT 0,
  total_latency_ms BIGINT NOT NULL DEFAULT 0,
  completed_at TIMESTAMPTZ(3),
  cancelled_at TIMESTAMPTZ(3),
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  CONSTRAINT fk_task_attempts_task_id FOREIGN KEY (task_id) REFERENCES tasks(task_id) ON DELETE CASCADE,
  CONSTRAINT fk_task_attempts_lease_id FOREIGN KEY (lease_id) REFERENCES task_leases(id) ON DELETE CASCADE,
  CONSTRAINT uq_task_attempts_task_attempt_no UNIQUE (task_id, attempt_no),
  CONSTRAINT uq_task_attempts_lease_id UNIQUE (lease_id),
  CONSTRAINT ck_task_attempts_status CHECK (status IN ('running', 'completed', 'failed', 'requeued', 'cancelled')),
  CONSTRAINT ck_task_attempts_attempt_no_positive CHECK (attempt_no > 0),
  CONSTRAINT ck_task_attempts_ids_valid CHECK (river_job_id >= 0),
  CONSTRAINT ck_task_attempts_terminal_consistency CHECK (
    (
      status = 'running'
      AND completed_at IS NULL
      AND cancelled_at IS NULL
      AND failure_stage = ''
      AND failure_category = ''
      AND error_msg = ''
    )
    OR (
      status = 'completed'
      AND completed_at IS NOT NULL
      AND cancelled_at IS NULL
      AND failure_stage = ''
      AND failure_category = ''
      AND error_msg = ''
    )
    OR (
      status IN ('failed', 'requeued')
      AND completed_at IS NOT NULL
      AND cancelled_at IS NULL
      AND btrim(failure_stage) <> ''
      AND btrim(failure_category) <> ''
      AND btrim(error_msg) <> ''
    )
    OR (
      status = 'cancelled'
      AND completed_at IS NULL
      AND cancelled_at IS NOT NULL
      AND btrim(failure_stage) <> ''
      AND failure_category = 'cancelled'
      AND btrim(error_msg) <> ''
    )
  ),
  CONSTRAINT ck_task_attempts_latency_non_negative CHECK (
    provider_latency_ms >= 0
    AND finalize_latency_ms >= 0
    AND total_latency_ms >= 0
  )
);

CREATE INDEX idx_task_attempts_task_created_at ON task_attempts (task_id, created_at DESC);
CREATE INDEX idx_task_attempts_status_created_at ON task_attempts (status, created_at DESC);
CREATE INDEX idx_task_attempts_failure_category_created_at ON task_attempts (failure_category, created_at DESC) WHERE failure_category <> '';
CREATE INDEX idx_task_attempts_running_created_at ON task_attempts (created_at) WHERE status = 'running';
CREATE INDEX idx_task_attempts_terminal_completed_at ON task_attempts (completed_at DESC, id) WHERE completed_at IS NOT NULL AND status IN ('completed', 'failed', 'requeued', 'cancelled');
CREATE INDEX idx_task_attempts_failed_category_completed_at ON task_attempts (failure_category, completed_at DESC) WHERE status = 'failed' AND completed_at IS NOT NULL AND failure_category <> '';

CREATE TABLE task_cancellations (
  task_id VARCHAR(64) PRIMARY KEY,
  expires_at TIMESTAMPTZ(3) NOT NULL,
  created_at TIMESTAMPTZ(3) NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ(3) NOT NULL DEFAULT now()
);

CREATE INDEX idx_task_cancellations_expires_at ON task_cancellations (expires_at);
