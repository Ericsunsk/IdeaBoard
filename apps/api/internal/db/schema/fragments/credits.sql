RETURNS trigger AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM credit_transactions
    WHERE transaction_id = NEW.transaction_id
      AND xmin = pg_current_xact_id()::xid
  ) THEN
    RAISE EXCEPTION 'credit postings must be inserted in the transaction that created their ledger transaction';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

