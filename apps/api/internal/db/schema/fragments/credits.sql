  CONSTRAINT ck_credit_transactions_reason CHECK (btrim(reason) <> ''),
  CONSTRAINT ck_credit_transactions_business_reference CHECK (btrim(business_reference_type) <> '' AND btrim(business_reference_id) <> ''),
