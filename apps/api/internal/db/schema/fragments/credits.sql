CREATE OR REPLACE FUNCTION prevent_credit_ledger_mutation()
RETURNS trigger AS $$
BEGIN
  RAISE EXCEPTION '% is immutable; append a reversing credit transaction instead', TG_TABLE_NAME;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER prevent_credit_transactions_mutation
BEFORE UPDATE OR DELETE ON credit_transactions
FOR EACH ROW EXECUTE FUNCTION prevent_credit_ledger_mutation();

