package tasks

import (
	"encoding/json"
	"fmt"

	"ideaboard/api/internal/workflow/paramkeys"
)

// SchemaVersion tracks the WorkflowTaskParams schema carried by task records.
const CurrentParamsSchemaVersion = 4

// WorkflowTaskParams is the typed contract for task parameters flowing
// from frontend submit through API, River, and into the worker/provider layer.
type WorkflowTaskParams struct {
	SchemaVersion int `json:"schema_version"`

	// Feature routing.
	Feature string `json:"feature,omitempty"`

	// Runtime media refs. Provider adapters flatten this object at the edge.
	Media *MediaInputs `json:"media,omitempty"`

	// Generation controls shared by multiple providers.
	Controls *GenerationControls `json:"controls,omitempty"`

	// Generation is the immutable, provider-independent request snapshot
	// captured before Task submission. Provider adapters must treat it as a
	// fact snapshot and derive their own request at the runtime boundary.
	Generation *GenerationRequestSnapshot `json:"generation,omitempty"`

	// ExecutionPlan is the opaque, versioned Workflow contract compiled at
	// intake. Tasking persists it without interpreting or duplicating Workflow
	// enums; routing and runtime decode it through the Workflow module.
	ExecutionPlan json.RawMessage `json:"execution_plan"`

	// Feature-specific canonical prompt contracts. Keep these in sync with
	// workflow/prompt_contract.go and SYSTEM_PROMPT.md.
	Variation *VariationsParams  `json:"variation,omitempty"`
	Outpaint  *OutpaintParams    `json:"outpaint,omitempty"`
	HD        *HDUpscaleParams   `json:"hd,omitempty"`
	Fusion    *StyleFusionParams `json:"fusion,omitempty"`

	// Provider hints (passthrough, not validated).
	// Extra carries provider-specific parameters that don't have a
	// first-class typed field. Consumers MUST NOT rely on Extra keys
	// for security or correctness — only for provider API shaping.
	Extra map[string]interface{} `json:"extra,omitempty"`
}

// GenerationRequestSnapshot records the user intent and resolved workflow
// inputs used to create a Task. It deliberately contains no provider model,
// account, or endpoint selection.
type GenerationRequestSnapshot struct {
	SchemaVersion        int                     `json:"schema_version"`
	Feature              string                  `json:"feature"`
	Primitive            string                  `json:"primitive"`
	UserPrompt           string                  `json:"user_prompt"`
	SystemPrompt         string                  `json:"system_prompt"`
	CompiledPrompt       string                  `json:"compiled_prompt"`
	TemplateVersion      string                  `json:"template_version,omitempty"`
	TemplateFingerprint  string                  `json:"template_fingerprint"`
	Seed                 uint64                  `json:"seed"`
	Controls             *GenerationControls     `json:"controls,omitempty"`
	Media                []GenerationMediaIntent `json:"media,omitempty"`
	RequestedOutputCount int                     `json:"requested_output_count"`
}

// GenerationMediaIntent is an ordered, role-aware durable media intent.
type GenerationMediaIntent struct {
	InputIndex int     `json:"input_index"`
	Role       string  `json:"role"`
	AssetID    int64   `json:"asset_id"`
	Weight     float64 `json:"weight,omitempty"`

	// Source exists only before task persistence to materialize an Asset.
	Source string `json:"-"`
}

const (
	MediaRoleInput     = "input"
	MediaRoleOriginal  = "original"
	MediaRoleReference = "reference"
	MediaRoleMask      = "mask"
)

func IsGenerationMediaRole(role string) bool {
	switch role {
	case MediaRoleInput, MediaRoleOriginal, MediaRoleReference, MediaRoleMask:
		return true
	default:
		return false
	}
}

type MediaInputs struct {
	Inputs     []MediaRef `json:"inputs,omitempty"`
	References []MediaRef `json:"references,omitempty"`
	Mask       *MediaRef  `json:"mask,omitempty"`
	Original   *MediaRef  `json:"original,omitempty"`
	UseMask    *bool      `json:"use_mask,omitempty"`
}

type MediaRef struct {
	AssetID int64   `json:"asset_id"`
	Role    string  `json:"role,omitempty"`
	Weight  float64 `json:"weight,omitempty"`

	// Source exists only before task persistence to materialize an Asset.
	Source string `json:"-"`
}

// RuntimeMediaInputs holds provider-safe URLs generated by the Worker. It is
// never serialized into Task Params.
type RuntimeMediaInputs struct {
	Inputs     []RuntimeMediaRef `json:"-"`
	References []RuntimeMediaRef `json:"-"`
	Mask       *RuntimeMediaRef  `json:"-"`
	Original   *RuntimeMediaRef  `json:"-"`
	UseMask    *bool             `json:"-"`
}

type RuntimeMediaRef struct {
	URL    string
	Role   string
	Weight float64
}

// ApplyGenerationMediaFacts binds prepared Asset identity into the canonical
// typed media shape before Task persistence.
func ApplyGenerationMediaFacts(media *MediaInputs, intents []GenerationMediaIntent) (*MediaInputs, error) {
	if media == nil {
		if len(intents) == 0 {
			return nil, nil
		}
		return nil, fmt.Errorf("canonical media inputs are required")
	}
	copyMedia := *media
	copyMedia.Inputs = append([]MediaRef(nil), media.Inputs...)
	copyMedia.References = append([]MediaRef(nil), media.References...)
	if media.Original != nil {
		original := *media.Original
		copyMedia.Original = &original
	}
	if media.Mask != nil {
		mask := *media.Mask
		copyMedia.Mask = &mask
	}
	if media.UseMask != nil {
		useMask := *media.UseMask
		copyMedia.UseMask = &useMask
	}

	intentIndex := 0
	apply := func(ref *MediaRef) error {
		if ref == nil || intentIndex >= len(intents) {
			return fmt.Errorf("canonical media facts do not match typed inputs")
		}
		intent := intents[intentIndex]
		if intent.InputIndex != intentIndex || intent.AssetID <= 0 || !IsGenerationMediaRole(intent.Role) || intent.Role != ref.Role {
			return fmt.Errorf("canonical media fact %d is invalid", intentIndex)
		}
		ref.AssetID = intent.AssetID
		ref.Source = ""
		intentIndex++
		return nil
	}
	for index := range copyMedia.Inputs {
		if err := apply(&copyMedia.Inputs[index]); err != nil {
			return nil, err
		}
	}
	for index := range copyMedia.References {
		if err := apply(&copyMedia.References[index]); err != nil {
			return nil, err
		}
	}
	if copyMedia.Original != nil {
		if err := apply(copyMedia.Original); err != nil {
			return nil, err
		}
	}
	if copyMedia.Mask != nil {
		if err := apply(copyMedia.Mask); err != nil {
			return nil, err
		}
	}
	if intentIndex != len(intents) {
		return nil, fmt.Errorf("canonical media facts do not match typed inputs")
	}
	return &copyMedia, nil
}

