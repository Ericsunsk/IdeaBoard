package worker

// Cross-module integration (#821, Phase 4-04 of #809): the three restored
// postgres stores (library folders/assets, workspace media
// uploads/assets, workspace tasks) working together behind fixture
// schemas.
//
// Fixture strategy (NOT the canonical schema.sql snapshot, which is
// broken — parent #809 scope): minimal throwaway schemas with the
// verbatim table definitions the three stores touch (users, workspaces,
// upload_sessions, media_assets, media_asset_derivatives,
// billing_accounts, tasks, task_outputs, library_folders,
// library_assets), following the #818/#820 fixture-DDL pattern. Tests
// SKIP gracefully without API_TEST_DATABASE_DSN.
//
// Scenarios (issue #821):
//  1. Task + Media: task takes a completed media asset as input, completes
//     with that asset as output, ListTaskAssets returns the public_id.
//  2. Library + Media: upload completes -> provider reference saved into a
//     library folder -> retrieved by folder.
//  3. Task + Library: task completes with a remote output -> the output URL
//     is saved as a library asset (caller-driven composition; no automatic
//     task->library hook exists — auto-add is Phase-4b).
//  4. Workspace isolation: A cannot touch B across all three modules.
//  5. Settlement: workspacetasks.Service Create over the REAL postgres
//     store with stub quoter/holder/queue proves Quote->Hold->Insert->
//     Enqueue plus enqueue-failure rollback (row deleted, hold released).
//     These stubs lack the Tx seams, so this scenario exercises the
//     compensating fallback; the single-transaction boundary itself is
//     proven in workspacetasks/settle_atomic_test.go (fixture DB, real
//     Credits ledger + Billing catalog).
//
// What this does NOT prove (documented residuals): actual image generation
// (worker consumes workspace_task_execute in Phase-4b), derivative rendering
// (renderer nil), library materialization (503), single-tx billing.

