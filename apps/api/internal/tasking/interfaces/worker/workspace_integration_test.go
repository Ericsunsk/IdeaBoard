type integrationHolder struct {
	mu       sync.Mutex
	holds    map[string]int64
	released map[string]int64
}

func newIntegrationHolder() *integrationHolder {
	return &integrationHolder{holds: map[string]int64{}, released: map[string]int64{}}
}

func (h *integrationHolder) Hold(ctx context.Context, userID int64, amount int64, key, taskID string) (string, error) {
	h.mu.Lock()
	defer h.mu.Unlock()
	holdID := "hold_" + taskID
	h.holds[holdID] = amount
	return holdID, nil
}

func (h *integrationHolder) Capture(ctx context.Context, holdID string, amount int64, taskID string) error {
	return nil
}

func (h *integrationHolder) Release(ctx context.Context, holdID string, amount int64, taskID string) error {
	h.mu.Lock()
	defer h.mu.Unlock()
	h.released[holdID] = amount
	delete(h.holds, holdID)
	return nil
}

type integrationQueue struct {
	mu       sync.Mutex
	enqueued []string
	failNext error
}

func (q *integrationQueue) Enqueue(ctx context.Context, task *workspacetasks.WorkspaceTask) error {
	q.mu.Lock()
	defer q.mu.Unlock()
	if q.failNext != nil {
		err := q.failNext
		q.failNext = nil
		return err
	}
	q.enqueued = append(q.enqueued, task.ID)
	return nil
}

// Scenario 5: settlement over the real postgres store with compensating
// rollback on enqueue failure.
func TestWorkspaceIntegrationSettlement(t *testing.T) {
	env := openWorkspaceIntegrationEnv(t)
	ctx := context.Background()

	quoter := &integrationQuoter{}
	holder := newIntegrationHolder()
	queue := &integrationQueue{}
	service := workspacetasks.NewService(workspacetasks.ServiceDeps{
		Tasks: env.tasks, Quoter: quoter, Holder: holder, Queue: queue, Models: workspaceTestModelResolver{},
	})

	created, err := service.Create(ctx, workspacetasks.CreateInput{
		WorkspaceID: env.wsA, OwnerUserID: env.userA,
		WorkflowKind: "render", Quantity: 1, Resolution: "default",
	}, "settle-key-1")
	if err != nil {
		t.Fatalf("settlement Create: %v", err)
	}
	stored, err := env.tasks.GetTask(ctx, env.wsA, created.ID)
	if err != nil || stored.Status != workspacetasks.StatusPending {
		t.Fatalf("stored task = (%+v, %v), want pending row", stored, err)
	}
	queue.mu.Lock()
	enqueued := len(queue.enqueued)
	queue.mu.Unlock()
	if enqueued != 1 {
		t.Fatalf("enqueued = %d, want 1", enqueued)
	}
	holder.mu.Lock()
	_, held := holder.holds["hold_"+created.ID]
	holder.mu.Unlock()
	if !held {
		t.Fatal("hold missing after settlement Create")
	}

	// Enqueue failure rolls back: no row, hold released.
	queue.mu.Lock()
	queue.failNext = errors.New("river unavailable")
	queue.mu.Unlock()
	failed, err := service.Create(ctx, workspacetasks.CreateInput{
		WorkspaceID: env.wsA, OwnerUserID: env.userA,
		WorkflowKind: "render", Quantity: 1, Resolution: "default",
	}, "settle-key-2")
	if err == nil {
		t.Fatalf("settlement Create with dead queue = (%v, nil), want error", failed)
	}
	holder.mu.Lock()
	released := len(holder.released)
	holder.mu.Unlock()
	if released != 1 {
		t.Fatalf("released holds = %d, want 1 (rollback)", released)
	}
}

