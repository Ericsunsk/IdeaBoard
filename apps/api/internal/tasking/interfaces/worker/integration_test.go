type integrationHolder struct {
	mu       sync.Mutex
	holds    map[string]int64
	released map[string]int64
}

func newIntegrationHolder() *integrationHolder {
	return &integrationHolder{holds: map[string]int64{}, released: map[string]int64{}}
}

func (h *integrationHolder) Hold(ctx context.Context, billingAccountID, actorUserID int64, amount int64, key, taskID string) (string, error) {
	h.mu.Lock()
	defer h.mu.Unlock()
	holdID := "hold_" + taskID
	h.holds[holdID] = amount
	return holdID, nil
}

func (h *integrationHolder) Capture(ctx context.Context, billingAccountID, actorUserID int64, holdID string, amount int64, taskID string) error {
	return nil
}

func (h *integrationHolder) Release(ctx context.Context, billingAccountID, actorUserID int64, holdID string, amount int64, taskID string) error {
	h.mu.Lock()
	defer h.mu.Unlock()
	h.released[holdID] = amount
	delete(h.holds, holdID)
	return nil
}

// HoldInTx serves the settlement-transaction seam from the same maps and
// registers its rollback undo: a rolled-back submit strands no fake hold.
// (Production holds ride the credits transaction itself; see
// workspacetasks/settle_test.go.)
func (h *integrationHolder) HoldInTx(ctx context.Context, tx pgx.Tx, billingAccountID, actorUserID int64, amount int64, key, taskID string) (string, error) {
	holdID, err := h.Hold(ctx, billingAccountID, actorUserID, amount, key, taskID)
	if err != nil {
		return "", err
	}
	if holdID != "" {
		workerOnRollback(tx, func() {
			h.mu.Lock()
			defer h.mu.Unlock()
			delete(h.holds, holdID)
		})
	}
	return holdID, nil
}

func (h *integrationHolder) CaptureInTx(ctx context.Context, _ pgx.Tx, billingAccountID, actorUserID int64, holdID string, amount int64, taskID string) (string, error) {
	if err := h.Capture(ctx, billingAccountID, actorUserID, holdID, amount, taskID); err != nil {
		return "", err
	}
	return "", nil
}

func (h *integrationHolder) ReleaseInTx(ctx context.Context, _ pgx.Tx, billingAccountID, actorUserID int64, holdID string, amount int64, taskID string) (string, error) {
	if err := h.Release(ctx, billingAccountID, actorUserID, holdID, amount, taskID); err != nil {
		return "", err
	}
	return "", nil
}

type integrationQueue struct {
	mu       sync.Mutex
	enqueued []string
	failNext error
}

func (q *integrationQueue) Enqueue(ctx context.Context, task *workspacetasks.WorkspaceTask) error {
	q.mu.Lock()
	defer q.mu.Unlock()
	if q.failNext != nil {
		err := q.failNext
		q.failNext = nil
		return err
	}
	q.enqueued = append(q.enqueued, task.ID)
	return nil
}

// EnqueueInTx serves the settlement-transaction seam from the same queue
// and registers its rollback undo.
func (q *integrationQueue) EnqueueInTx(ctx context.Context, tx pgx.Tx, task *workspacetasks.WorkspaceTask) error {
	if err := q.Enqueue(ctx, task); err != nil {
		return err
	}
	workerOnRollback(tx, func() {
		q.mu.Lock()
		defer q.mu.Unlock()
		for i, id := range q.enqueued {
			if id == task.ID {
				q.enqueued = append(q.enqueued[:i], q.enqueued[i+1:]...)
				return
			}
		}
	})
	return nil
}

// Scenario 5: settlement over the real postgres store with transactional
// rollback on enqueue failure.
func TestWorkspaceIntegrationSettlement(t *testing.T) {
	env := openWorkspaceIntegrationEnv(t)
	ctx := context.Background()

	quoter := &integrationQuoter{}
	holder := newIntegrationHolder()
	queue := &integrationQueue{}
	assets := &workspacemedia.TaskAssetAdapter{Store: env.media}
	txStore := newTxPGServiceStore(env.tasks)
	// TaskBilling stays nil: the fixture schema carries no billing fact
	// tables (the billing projection is proven in
	// workspacetasks/settle_test.go); the claim fence is in-memory for the
	// same reason.
	service := workspacetasks.NewService(workspacetasks.ServiceDeps{
		TaskRead: env.tasks, TaskLifecycle: txStore, Quoter: quoter, Holder: holder, Queue: queue,
		Assets: assets, Resolver: allowTestPoolResolver(),
		SnapshotSaver: workerNoopSnapshotSaver,
		Acceptance:    &workerTestAcceptance{assets: assets},
	})

	created, err := service.Create(ctx, workspacetasks.CreateInput{
		WorkspaceID: env.wsA, OwnerUserID: env.userA,
		Service: "render", Quantity: 1, Resolution: "",
	}, "settle-key-1")
	if err != nil {
		t.Fatalf("settlement Create: %v", err)
	}
	stored, err := env.tasks.GetTask(ctx, env.wsA, created.ID)
	if err != nil || stored.Status != workspacetasks.StatusPending {
		t.Fatalf("stored task = (%+v, %v), want pending row", stored, err)
	}
	queue.mu.Lock()
	enqueued := len(queue.enqueued)
	queue.mu.Unlock()
	if enqueued != 1 {
		t.Fatalf("enqueued = %d, want 1", enqueued)
	}
	holder.mu.Lock()
	_, held := holder.holds["hold_"+created.ID]
	holder.mu.Unlock()
	if !held {
		t.Fatal("hold missing after settlement Create")
	}
	var outboxCount int
	if err := env.pool.QueryRow(ctx, `SELECT count(*) FROM task_status_event_outbox WHERE task_id=$1 AND status='pending'`, created.ID).Scan(&outboxCount); err != nil {
		t.Fatalf("read submission outbox: %v", err)
	}
	if outboxCount != 1 {
		t.Fatalf("submission outbox rows = %d, want 1", outboxCount)
	}

	// Enqueue failure rolls back: no row, no stranded hold, no compensating
	// release (the transaction owns the rollback now).
	queue.mu.Lock()
	queue.failNext = errors.New("river unavailable")
	queue.mu.Unlock()
	failed, err := service.Create(ctx, workspacetasks.CreateInput{
		WorkspaceID: env.wsA, OwnerUserID: env.userA,
		Service: "render", Quantity: 1, Resolution: "",
	}, "settle-key-2")
	if err == nil {
		t.Fatalf("settlement Create with dead queue = (%v, nil), want error", failed)
	}
	holder.mu.Lock()
	holds, released := len(holder.holds), len(holder.released)
	holder.mu.Unlock()
	if holds != 1 {
		t.Fatalf("holds = %d, want 1 (the successful submit only; rollback removes the failed hold)", holds)
	}
	if released != 0 {
		t.Fatalf("released holds = %d, want 0 (no compensating release on rollback)", released)
	}
	taskCount, err := env.tasks.CountTasks(ctx, env.wsA)
	if err != nil {
		t.Fatalf("read tasks after failed submission: %v", err)
	}
	if taskCount != 1 {
		t.Fatalf("tasks after failed submission = %d, want only the successful submission", taskCount)
	}
	if err := env.pool.QueryRow(ctx, `SELECT count(*) FROM task_status_event_outbox WHERE workspace_id=$1`, env.wsA).Scan(&outboxCount); err != nil {
		t.Fatalf("read outbox after failed submission: %v", err)
	}
	if outboxCount != 1 {
		t.Fatalf("outbox rows after failed submission = %d, want only the successful submission", outboxCount)
	}
}

