type mediaTestEnv struct {
	pool  *pgxpool.Pool
	svc   *Service
	wsA   string
	wsB   string
	owner int64
}

func openMediaTestEnv(t *testing.T) *mediaTestEnv {
	t.Helper()
	raw := testenv.GetOrSkip(t, "API_TEST_DATABASE_DSN", "set API_TEST_DATABASE_DSN to run PostgreSQL integration tests")
	ctx := context.Background()
	cfg, err := pgxpool.ParseConfig(raw)
	if err != nil {
		t.Fatalf("parse test database dsn: %v", err)
	}
	admin, err := pgxpool.NewWithConfig(ctx, cfg)
	if err != nil {
		t.Fatalf("open test database: %v", err)
	}
	schema := fmt.Sprintf("media_test_%d_%d", os.Getpid(), time.Now().UnixNano())
	if _, err := admin.Exec(ctx, `CREATE SCHEMA `+schema); err != nil {
		admin.Close()
		t.Fatalf("create test schema: %v", err)
	}
	t.Cleanup(func() {
		_, _ = admin.Exec(context.Background(), `DROP SCHEMA `+schema+` CASCADE`)
		admin.Close()
	})
	schemaCfg, err := pgxpool.ParseConfig(raw)
	if err != nil {
		t.Fatalf("parse test database dsn: %v", err)
	}
	schemaCfg.ConnConfig.RuntimeParams["search_path"] = schema + ",public"
	pool, err := pgxpool.NewWithConfig(ctx, schemaCfg)
	if err != nil {
		t.Fatalf("open isolated test pool: %v", err)
	}
	t.Cleanup(pool.Close)
	if _, err := pool.Exec(ctx, mediaTestDDL); err != nil {
		t.Fatalf("apply media fixture ddl: %v", err)
	}
	var userID int64
	if err := pool.QueryRow(ctx,
		`INSERT INTO users (display_name, storage_uid) VALUES ('media test user', 'M00001') RETURNING id`,
	).Scan(&userID); err != nil {
		t.Fatalf("seed test user: %v", err)
	}
	seedWorkspace := func(publicID, name string) {
		t.Helper()
		if _, err := pool.Exec(ctx,
			`INSERT INTO workspaces (public_id, owner_user_id, name) VALUES ($1, $2, $3)`,
			publicID, userID, name,
		); err != nil {
			t.Fatalf("seed workspace %s: %v", publicID, err)
		}
	}
	wsA := fmt.Sprintf("ws_mediatest_a_%d", time.Now().UnixNano()%1000000)
	wsB := fmt.Sprintf("ws_mediatest_b_%d", time.Now().UnixNano()%1000000)
	seedWorkspace(wsA, "media-a")
	seedWorkspace(wsB, "media-b")
	return &mediaTestEnv{pool: pool, svc: NewService(pool), wsA: wsA, wsB: wsB, owner: userID}
}

