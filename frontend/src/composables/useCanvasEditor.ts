import type { Ref } from 'vue'
import { useCanvasKeyboardShortcuts } from './useCanvasKeyboardShortcuts'
import { useCanvasPointerInteractions } from './useCanvasPointerInteractions'
import { useCanvasSurfaceInteractions } from './useCanvasSurfaceInteractions'
import { useCanvasEditorUiState } from './useCanvasEditorUiState'
import {
  createCanvasKeyboardBindings,
  createCanvasPointerBindings,
  createCanvasSurfaceBindings,
} from './canvasEditorBindings'
import {
  useCanvasSelectionState,
  type DraggableNode,
  type NodeDragKind,
} from './useCanvasSelectionState'
import type { UseCanvasEditorOptions } from './canvasEditorTypes'

export function useCanvasEditor(options: UseCanvasEditorOptions) {
  const {
    isDuplicateModifierPressed,
    nodeContextMenu,
    isPanning,
    isSelecting,
    isDraggingItem,
    draggingNodeKeys,
    isResizingItem,
    isSpacePressed,
    selectionRect,
  } = useCanvasEditorUiState()

  function isNodeDragging(kind: NodeDragKind, id: number): boolean {
    return draggingNodeKeys.value.includes(getNodeSelectionKey(kind, id))
  }

  const {
    selectedIds,
    selectedNodeKeys,
    activeImageActionId,
    activeImageNodeId,
    activePromptNodeId,
    activeModelNodeId,
    activeMaskNodeId,
    activeColorNodeId,
    activeEditNodeId,
    activeFusionNodeId,
    activeEnhanceNodeId,
    activeTryOnNodeId,
    activePaletteNodeId,
    activeGenerateNodeId,
    clearActiveNodes,
    getNodeSelectionKey,
    resolveNodeBySelectionKey,
    isNodeSelected,
    isNodeActive,
    clearSelectedNodeKeys,
    removeSelectedNodeKey,
    activateImageNode,
    activatePromptNode,
    activateModelNode,
    activateMaskNode,
    activateColorNode,
    activateEditNode,
    activateFusionNode,
    activateEnhanceNode,
    activateTryOnNode,
    activatePaletteNode,
    activateGenerateNode,
    activateNodeByKind,
    clearCanvasQuickActionState,
    clearSelectedIds,
    deleteActiveNode,
    deleteSelectedCanvasImages,
    removeSelectedId,
    focusSelectedItem,
    hasActiveNodeSelection,
    clearActiveNodeSelection,
  } = useCanvasSelectionState({
    messages: options.messages,
    imageNodes: options.imageNodes,
    promptNodes: options.promptNodes,
    modelNodes: options.modelNodes,
    maskNodes: options.maskNodes,
    colorNodes: options.colorNodes,
    editNodes: options.editNodes,
    fusionNodes: options.fusionNodes,
    enhanceNodes: options.enhanceNodes,
    tryOnNodes: options.tryOnNodes,
    paletteNodes: options.paletteNodes,
    generateNodes: options.generateNodes,
    showStyleStrengthControl: options.showStyleStrengthControl,
    canvasX: options.canvasX,
    canvasY: options.canvasY,
    zoomLevel: options.zoomLevel,
    deleteImageNode: options.deleteImageNode,
    deletePromptNode: options.deletePromptNode,
    deleteModelNode: options.deleteModelNode,
    deleteMaskNode: options.deleteMaskNode,
    deleteColorNode: options.deleteColorNode,
    deleteEditNode: options.deleteEditNode,
    deleteFusionNode: options.deleteFusionNode,
    deleteEnhanceNode: options.deleteEnhanceNode,
    deleteTryOnNode: options.deleteTryOnNode,
    deletePaletteNode: options.deletePaletteNode,
    deleteGenerateNode: options.deleteGenerateNode,
  })

  const {
    closeNodeContextMenu,
    resetPointerUiState,
    onCanvasContextMenu,
    onCanvasMouseDown,
    onItemMouseDown,
    onItemContextMenu,
    onImageNodeMouseDown,
    onPromptNodeMouseDown,
    onModelNodeMouseDown,
    onMaskNodeMouseDown,
    onColorNodeMouseDown,
    onEditNodeMouseDown,
    onFusionNodeMouseDown,
    onEnhanceNodeMouseDown,
    onTryOnNodeMouseDown,
    onPaletteNodeMouseDown,
    onGenerateNodeMouseDown,
    onResizeMouseDown,
  } = useCanvasPointerInteractions(createCanvasPointerBindings(options, {
    isDuplicateModifierPressed,
    nodeContextMenu,
    isPanning,
    isSelecting,
    isDraggingItem,
    draggingNodeKeys,
    isResizingItem,
    isSpacePressed,
    selectionRect,
  }, {
    selectedIds,
    selectedNodeKeys,
    activeImageActionId,
    activeImageNodeId,
    activePromptNodeId,
    activeModelNodeId,
    activeMaskNodeId,
    activeColorNodeId,
    activeEditNodeId,
    activeFusionNodeId,
    activeEnhanceNodeId,
    activeTryOnNodeId,
    activePaletteNodeId,
    activeGenerateNodeId,
    clearActiveNodes,
    clearSelectedNodeKeys,
    removeSelectedNodeKey,
    activateNodeByKind,
    isNodeActive,
    resolveNodeBySelectionKey,
    getNodeSelectionKey,
    clearCanvasQuickActionState,
    hasActiveNodeSelection,
    clearActiveNodeSelection,
    clearSelectedIds,
    deleteActiveNode,
    deleteSelectedCanvasImages,
  }))

  function resetEditorUiState() {
    selectedIds.value = []
    clearSelectedNodeKeys()
    resetPointerUiState()
  }

  const { readNodeImageDropPayload, handleDrop } = useCanvasSurfaceInteractions(
    createCanvasSurfaceBindings(options, { selectedIds, activeImageActionId }, closeNodeContextMenu),
  )

  useCanvasKeyboardShortcuts(
    createCanvasKeyboardBindings(options, {
      isDuplicateModifierPressed,
      isSpacePressed,
      nodeContextMenu,
    }, {
      activeImageActionId,
      clearCanvasQuickActionState,
      hasActiveNodeSelection,
      clearActiveNodeSelection,
      selectedIds,
      clearSelectedIds,
      deleteActiveNode,
      deleteSelectedCanvasImages,
    }, closeNodeContextMenu),
  )

  return {
    selectedIds,
    selectedNodeKeys,
    activeImageActionId,
    isDuplicateModifierPressed,
    activeImageNodeId,
    activePromptNodeId,
    activeModelNodeId,
    activeMaskNodeId,
    activeColorNodeId,
    activeEditNodeId,
    activeFusionNodeId,
    activeEnhanceNodeId,
    activeTryOnNodeId,
    activePaletteNodeId,
    activeGenerateNodeId,
    nodeContextMenu,
    isPanning,
    isSelecting,
    isDraggingItem,
    isResizingItem,
    isSpacePressed,
    selectionRect,
    activateImageNode,
    activatePromptNode,
    activateModelNode,
    activateMaskNode,
    activateColorNode,
    activateEditNode,
    activateFusionNode,
    activateEnhanceNode,
    activateTryOnNode,
    activatePaletteNode,
    activateGenerateNode,
    isNodeSelected,
    isNodeDragging,
    clearActiveNodes,
    closeNodeContextMenu,
    resetEditorUiState,
    onCanvasContextMenu,
    onCanvasMouseDown,
    onItemMouseDown,
    onItemContextMenu,
    onImageNodeMouseDown,
    onPromptNodeMouseDown,
    onModelNodeMouseDown,
    onMaskNodeMouseDown,
    onColorNodeMouseDown,
    onEditNodeMouseDown,
    onFusionNodeMouseDown,
    onEnhanceNodeMouseDown,
    onTryOnNodeMouseDown,
    onPaletteNodeMouseDown,
    onGenerateNodeMouseDown,
    onResizeMouseDown,
    readNodeImageDropPayload,
    handleDrop,
    clearSelectedIds,
    clearSelectedNodeKeys,
    removeSelectedNodeKey,
    removeSelectedId,
    focusSelectedItem,
  }
}
